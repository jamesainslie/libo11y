var csTypePattern = regexp.MustCompile(`^[A-Z][A-Za-z0-9_]*$`)

// errCsName reports a registry name the .NET library cannot carry.
var errCsName = errors.New("dotnet name")

// csPascalName converts a dotted, snake or kebab name to PascalCase, dropping an o11y. prefix.
func csPascalName(name string) string {
	return rustTypeName(name)
}

func csQuote(s string) string {
	raw, _ := json.Marshal(s)
	return string(raw)
}

func csQuoteAll(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = csQuote(n)
	}
	return out
}

func csHeader(b *strings.Builder, m *model) {
	b.WriteString("// <auto-generated/>\n")
	fmt.Fprintf(b, "// Code generated by specgen from spec/registry (spec %s). DO NOT EDIT.\n", m.specVersion)
	b.WriteString("#nullable enable\n\n")
}

type csEnum struct {
	typeName string
	key      string
	members  []enumMember
	names    []string
}

func (m *model) csEnums() ([]csEnum, error) {
	var enums []csEnum
	for _, a := range m.minted {
		if members := a.enumMembers(); len(members) > 0 {
			enums = append(enums, csEnum{typeName: csPascalName(a.ID), key: a.ID, members: members})
		}
	}
	if env := m.environmentValues(); len(env) > 0 {
		members := make([]enumMember, len(env))
		for i, v := range env {
			members[i] = enumMember{ID: v, Value: v}
		}
		enums = append(enums, csEnum{typeName: "DeploymentEnvironment", key: environmentKey, members: members})
	}
	types := map[string]string{}
	for i, e := range enums {
		if !csTypePattern.MatchString(e.typeName) || csKeywords[strings.ToLower(e.typeName)] {
			return nil, fmt.Errorf("%w: attribute %s: %q is not a C# type name", errCsName, e.key, e.typeName)
		}
		if other, dup := types[e.typeName]; dup {
			return nil, fmt.Errorf("%w: attributes %s and %s both become enum %s", errCsName, other, e.key, e.typeName)
		}
		if csReservedTypes[e.typeName] && e.key != environmentKey {
			return nil, fmt.Errorf("%w: attribute %s: enum %s would collide with a spec type", errCsName, e.key, e.typeName)
		}
		types[e.typeName] = e.key
		seen := map[string]string{}
		for _, member := range e.members {
			name := csPascalName(member.ID)
			if !csTypePattern.MatchString(name) || name == "All" || name == "IsValid" {
				return nil, fmt.Errorf("%w: attribute %s: member %s: %q is not a C# member name", errCsName, e.key, member.ID, name)
			}
			if other, dup := seen[name]; dup {
				return nil, fmt.Errorf("%w: attribute %s: members %s and %s both become %s", errCsName, e.key, other, member.ID, name)
			}
			seen[name] = member.ID
			enums[i].names = append(enums[i].names, name)
		}
	}
	return enums, nil
}

// genCsSpec renders dotnet/src/Libo11y.Spec/Generated/Spec.g.cs.
func genCsSpec(m *model) (string, error) {
	enums, err := m.csEnums()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	csHeader(&b, m)
	b.WriteString("using System.Collections.Frozen;\n")
	b.WriteString("using System.Collections.Generic;\n\n")
	b.WriteString("namespace Libo11y.Spec;\n\n")
	b.WriteString("public static class SpecConstants\n{\n")
	fmt.Fprintf(&b, "    public const string SchemaUrl = %s;\n", csQuote(m.schemaURL))
	fmt.Fprintf(&b, "    public const string SpecVersion = %s;\n", csQuote(m.specVersion))
	fmt.Fprintf(&b, "    public const string SemconvVersion = %s;\n", csQuote(m.semconvVersion))
	fmt.Fprintf(&b, "    public const string EventNameKey = %s;\n", csQuote("event.name"))
	b.WriteString("}\n")

	for _, e := range enums {
		fmt.Fprintf(&b, "\npublic static class %s\n{\n", e.typeName)
		for i, member := range e.members {
			fmt.Fprintf(&b, "    public const string %s = %s;\n", e.names[i], csQuote(member.Value))
		}
		fmt.Fprintf(&b, "\n    public static readonly FrozenSet<string> All = FrozenSet.ToFrozenSet(new string[] { %s });\n", strings.Join(e.names, ", "))
		b.WriteString("    public static bool IsValid(string value) => All.Contains(value);\n")
		b.WriteString("}\n")
	}

	writeGroup := func(className string, entries []string) error {
		seen := map[string]string{}
		fmt.Fprintf(&b, "\npublic static class %s\n{\n", className)
		for _, raw := range entries {
			name := csPascalName(raw)
			if !csTypePattern.MatchString(name) {
				return fmt.Errorf("%w: %s: %q is not a C# constant name", errCsName, raw, name)
			}
			if other, dup := seen[name]; dup {
				return fmt.Errorf("%w: %s and %s both become constant %s.%s", errCsName, other, raw, className, name)
			}
			seen[name] = raw
			fmt.Fprintf(&b, "    public const string %s = %s;\n", name, csQuote(raw))
		}
		b.WriteString("}\n")
		return nil
	}

	var attrKeys []string
	for _, a := range m.minted {
		attrKeys = append(attrKeys, a.ID)
	}
	attrKeys = append(attrKeys, m.copiedRefs()...)
	if err := writeGroup("SpecAttributes", attrKeys); err != nil {
		return "", err
	}

	var eventNames []string
	for _, ev := range m.events {
		eventNames = append(eventNames, ev.Name)
	}
	if err := writeGroup("SpecEvents", eventNames); err != nil {
		return "", err
	}

	var metricNames []string
	for _, mt := range m.metrics {
		metricNames = append(metricNames, mt.MetricName)
	}
	if err := writeGroup("SpecMetrics", metricNames); err != nil {
		return "", err
	}

	return b.String(), nil
}

func csRequirement(level string) string {
	switch level {
	case "required":
		return "Requirement.Required"
	case "conditionally_required":
		return "Requirement.ConditionallyRequired"
	case "opt_in":
		return "Requirement.OptIn"
	default:
		return "Requirement.Recommended"
	}
}

func csSensitivity(class string) (string, error) {
	switch class {
	case "public":
		return "Sensitivity.Public", nil
	case "internal":
		return "Sensitivity.Internal", nil
	case "pii":
		return "Sensitivity.Pii", nil
	case "secret":
		return "Sensitivity.Secret", nil
	default:
		return "", fmt.Errorf("unknown sensitivity class %q", class)
	}
}

func csCardinality(class string) (string, error) {
	switch class {
	case "enum":
		return "Cardinality.Enum", nil
	case "bounded":
		return "Cardinality.Bounded", nil
	case "unbounded":
		return "Cardinality.Unbounded", nil
	default:
		return "", fmt.Errorf("unknown cardinality class %q", class)
	}
}

func csInstrument(instrument string) (string, error) {
	switch instrument {
	case "counter":
		return "InstrumentKind.Counter", nil
	case "histogram":
		return "InstrumentKind.Histogram", nil
	case "gauge":
		return "InstrumentKind.Gauge", nil
	case "updowncounter":
		return "InstrumentKind.UpDownCounter", nil
	default:
		return "", fmt.Errorf("unknown instrument %q", instrument)
	}
}

func csStringArray(items []string) string {
	if len(items) == 0 {
		return "Array.Empty<string>()"
	}
	return "new string[] { " + strings.Join(csQuoteAll(items), ", ") + " }"
}

