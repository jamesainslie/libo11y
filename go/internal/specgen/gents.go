// Where the TypeScript artifacts land, inside the @libo11y/spec package.
const (
	tsSpecPath   = "ts/packages/spec/src/generated/spec.ts"
	tsTablesPath = "ts/packages/spec/src/generated/tables.ts"
)

// tsConst converts a dotted name to an upper snake-case TypeScript constant
// suffix, dropping an o11y. prefix: o11y.rum.view.name becomes
// RUM_VIEW_NAME.
func tsConst(name string) string {
	name = strings.TrimPrefix(name, "o11y.")
	return strings.ToUpper(strings.ReplaceAll(name, ".", "_"))
}

// tsMemberConst converts an enum member ID to its constant suffix with the
// same folding as tsConst: upper case, with each dot an underscore, so a
// member us.prod becomes US_PROD.
func tsMemberConst(id string) string {
	return strings.ToUpper(strings.ReplaceAll(id, ".", "_"))
}

// tsQuote renders s as a TypeScript string literal. JSON string syntax is a
// subset of JavaScript's, and encoding a Go string to JSON cannot fail.
func tsQuote(s string) string {
	raw, _ := json.Marshal(s)
	return string(raw)
}

// tsList renders names as a TypeScript array literal of strings.
func tsList(names []string) string {
	quoted := make([]string, len(names))
	for i, name := range names {
		quoted[i] = tsQuote(name)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

// tsRequirement normalizes a requirement level the way requirementConst
// does for Go: anything unrecognized is recommended.
func tsRequirement(level string) string {
	switch level {
	case "required", "conditionally_required", "opt_in":
		return level
	default:
		return "recommended"
	}
}

func tsHeader(b *strings.Builder, m *model) {
	fmt.Fprintf(b, "// Code generated by specgen from spec/registry (spec %s). DO NOT EDIT.\n\n", m.specVersion)
}

// genTSSpec renders spec.ts: identity constants, closed enums, key, event
// and metric name constants.
func genTSSpec(m *model) string {
	var b strings.Builder
	tsHeader(&b, m)
	b.WriteString("/** The schema URL stamped on every resource libo11y builds. */\n")
	fmt.Fprintf(&b, "export const SCHEMA_URL = %s;\n", tsQuote(m.schemaURL))
	b.WriteString("/** The libo11y specification version this package implements. */\n")
	fmt.Fprintf(&b, "export const SPEC_VERSION = %s;\n", tsQuote(m.specVersion))
	b.WriteString("/** The pinned OpenTelemetry semantic conventions version. */\n")
	fmt.Fprintf(&b, "export const SEMCONV_VERSION = %s;\n", tsQuote(m.semconvVersion))
	b.WriteString("/** The log attribute that carries an event's name. */\n")
	b.WriteString("export const EVENT_NAME_KEY = \"event.name\";\n")

	for _, a := range m.minted {
		members := a.enumMembers()
		if len(members) == 0 {
			continue
		}
		pairs := make([][2]string, len(members))
		for i, member := range members {
			pairs[i] = [2]string{member.ID, member.Value}
		}
		tsEnum(&b, goName(a.ID), tsConst(a.ID), tsConst(a.ID)+"_VALUES", a.ID, pairs)
	}
	if env := m.environmentValues(); len(env) > 0 {
		pairs := make([][2]string, len(env))
		for i, v := range env {
			pairs[i] = [2]string{v, v}
		}
		// ENVIRONMENT_VALUES is the Set in tables.ts, so the list takes
		// another name here.
		tsEnum(&b, "Environment", "ENVIRONMENT", "ENVIRONMENT_VALUES_LIST", "deployment.environment.name", pairs)
	}

	b.WriteString("\n// Attribute keys minted by the libo11y specification.\n")
	for _, a := range m.minted {
		fmt.Fprintf(&b, "export const ATTR_%s = %s;\n", tsConst(a.ID), tsQuote(a.ID))
	}
	if copied := m.copiedRefs(); len(copied) > 0 {
		b.WriteString("\n// Upstream attribute keys copied from the pinned registry snapshot.\n")
		for _, name := range copied {
			fmt.Fprintf(&b, "export const ATTR_%s = %s;\n", tsConst(name), tsQuote(name))
		}
	}
	b.WriteString("\n// Registered event names.\n")
	for _, ev := range m.events {
		fmt.Fprintf(&b, "export const EVENT_%s = %s;\n", tsConst(ev.Name), tsQuote(ev.Name))
	}
	if len(m.metrics) > 0 {
		b.WriteString("\n// Registered metric names.\n")
		for _, mt := range m.metrics {
			fmt.Fprintf(&b, "export const METRIC_%s = %s;\n", tsConst(mt.MetricName), tsQuote(mt.MetricName))
		}
	}
	return b.String()
}

// tsEnum writes a closed value set as a string-literal union type, one
// constant per member and a readonly array of every value. Each pair is a
// member's ID and its value.
func tsEnum(b *strings.Builder, typeName, constPrefix, listName, attrName string, members [][2]string) {
	values := make([]string, len(members))
	for i, member := range members {
		values[i] = tsQuote(member[1])
	}
	fmt.Fprintf(b, "\n/** The closed value set for `%s`. */\n", attrName)
	fmt.Fprintf(b, "export type %s = %s;\n", typeName, strings.Join(values, " | "))
	for _, member := range members {
		fmt.Fprintf(b, "export const %s_VALUE_%s = %s;\n", constPrefix, tsMemberConst(member[0]), tsQuote(member[1]))
	}
	fmt.Fprintf(b, "/** Every value of `%s`. */\n", attrName)
	fmt.Fprintf(b, "export const %s: readonly %s[] = [%s];\n", listName, typeName, strings.Join(values, ", "))
}

// tsTablesPreamble declares the table types.
const tsTablesPreamble = `/** How the redaction layer treats an attribute. A key with no entry is unclassified. */
export type Sensitivity = "public" | "internal" | "pii" | "secret";

/** A spec requirement level. */
export type Requirement = "required" | "conditionally_required" | "recommended" | "opt_in";

/** One attribute's place in the resource taxonomy. */
export interface ResourceAttrInfo {
  readonly tier: string;
  readonly requirement: Requirement;
  readonly source: string;
  readonly role: string;
}

/**
 * A registered event's contract. required lists literal keys the event must carry. requiredTemplates
 * lists template attributes the event satisfies with at least one <template>.<key> attribute.
 */
export interface EventInfo {
  readonly required: readonly string[];
  readonly requiredTemplates: readonly string[];
}
`

// genTSTables renders tables.ts. Keyed tables are Maps, so a lookup can
// never reach Object.prototype.
func genTSTables(m *model) (string, error) {
	var b strings.Builder
	tsHeader(&b, m)
	b.WriteString(tsTablesPreamble)

	b.WriteString("\n/** The tiered resource-attribute taxonomy. */\n")
	b.WriteString("export const RESOURCE: ReadonlyMap<string, ResourceAttrInfo> = new Map<string, ResourceAttrInfo>([\n")
	for _, tier := range m.tierOrder {
		for _, a := range m.tiers[tier] {
			fmt.Fprintf(&b, "  [%s, { tier: %s, requirement: %s, source: %s, role: %s }],\n",
				tsQuote(a.name()), tsQuote(tier), tsQuote(tsRequirement(a.requirement())),
				tsQuote(a.Annotations["o11y.source"]), tsQuote(a.Annotations["o11y.role"]))
		}
	}
	b.WriteString("]);\n")

	var tier0 []string
	for _, a := range m.tiers["tier0"] {
		if a.requirement() == "required" {
			tier0 = append(tier0, a.name())
		}
	}
	b.WriteString("\n/** The attributes setup requires at init. */\n")
	fmt.Fprintf(&b, "export const REQUIRED_TIER0: readonly string[] = %s;\n", tsList(tier0))

	b.WriteString("\n/** The base allowed set for deployment.environment.name. */\n")
	fmt.Fprintf(&b, "export const ENVIRONMENT_VALUES: ReadonlySet<string> = new Set<string>(%s);\n", tsList(m.environmentValues()))

	b.WriteString("\n/** Classifies every attribute the spec has an opinion on. */\n")
	b.WriteString("export const SENSITIVITY_OF: ReadonlyMap<string, Sensitivity> = new Map<string, Sensitivity>([\n")
	for _, name := range slices.Sorted(maps.Keys(m.classByName)) {
		class := m.classByName[name]
		if _, err := sensitivityConst(class); err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "  [%s, %s],\n", tsQuote(name), tsQuote(class))
	}
	b.WriteString("]);\n")

	b.WriteString("\n/** Maps each key a pre-spec release emitted to the spec key that replaces it. */\n")
	b.WriteString("export const LEGACY_KEYS: ReadonlyMap<string, string> = new Map<string, string>([\n")
	for _, name := range slices.Sorted(maps.Keys(m.legacyKeys)) {
		fmt.Fprintf(&b, "  [%s, %s],\n", tsQuote(name), tsQuote(m.legacyKeys[name]))
	}
	b.WriteString("]);\n")

	labels := make([]string, len(m.metricLabels))
	for i, a := range m.metricLabels {
		labels[i] = a.name()
	}
	b.WriteString("\n/** The only resource attributes permitted as effective metric labels. */\n")
	fmt.Fprintf(&b, "export const METRIC_RESOURCE_LABELS: readonly string[] = %s;\n", tsList(labels))

	b.WriteString("\n/** Registered event names mapped to their contracts. */\n")
	b.WriteString("export const EVENTS: ReadonlyMap<string, EventInfo> = new Map<string, EventInfo>([\n")
	for _, ev := range m.events {
		required, templates := m.eventRequirements(ev)
		fmt.Fprintf(&b, "  [%s, { required: %s, requiredTemplates: %s }],\n", tsQuote(ev.Name), tsList(required), tsList(templates))
	}
	b.WriteString("]);\n")

	b.WriteString("\n/** Span kinds registered by the spec mapped to their required attributes. */\n")
	b.WriteString("export const SPAN_REQUIRED: ReadonlyMap<string, readonly string[]> = new Map<string, readonly string[]>([\n")
	for _, sp := range m.spans {
		fmt.Fprintf(&b, "  [%s, %s],\n", tsQuote(sp.Annotations["o11y.span.kind"]), tsList(requiredNames(sp)))
	}
	b.WriteString("]);\n")

	b.WriteString("\n/** RUM span shapes mapped to their required attributes. */\n")
	b.WriteString("export const RUM_SPAN_REQUIRED: ReadonlyMap<string, readonly string[]> = new Map<string, readonly string[]>([\n")
	for _, sp := range m.rumSpans {
		fmt.Fprintf(&b, "  [%s, %s],\n", tsQuote(sp.Annotations["o11y.rum.span"]), tsList(requiredNames(sp)))
	}
	b.WriteString("]);\n")

	return b.String(), nil
}
