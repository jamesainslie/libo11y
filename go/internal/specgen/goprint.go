package main

import (
	"strconv"
	"strings"
	"unicode"
)

// tsGoPrintPath is where Go's printable ranges land for the TypeScript
// port of %q quoting. JavaScript's \p{...} classes follow the runtime's
// Unicode version, which differs from the Go toolchain's, so the table
// comes from Go itself.
const tsGoPrintPath = "ts/packages/spec/src/generated/goprint.ts"

// goPrintRanges returns the code points unicode.IsPrint accepts, which is
// the set strconv.Quote leaves unescaped, as sorted, inclusive [lo, hi]
// pairs flattened into one slice.
func goPrintRanges() []rune {
	var ranges []rune
	in := false
	for r := rune(0); r <= unicode.MaxRune; r++ {
		switch p := unicode.IsPrint(r); {
		case p && !in:
			ranges = append(ranges, r)
			in = true
		case !p && in:
			ranges = append(ranges, r-1)
			in = false
		}
	}
	if in {
		ranges = append(ranges, unicode.MaxRune)
	}
	return ranges
}

// genTSGoPrint renders goprint.ts: the goPrintRanges bounds as one
// numeric array, wrapped to stay within the formatter's line width.
func genTSGoPrint() string {
	var b strings.Builder
	b.WriteString("// Code generated by specgen from Go's unicode.IsPrint (Unicode " + unicode.Version + "). DO NOT EDIT.\n\n")
	b.WriteString("/**\n")
	b.WriteString(" * The code points Go's strconv.Quote prints as they are, as sorted, inclusive [lo, hi] pairs flattened\n")
	b.WriteString(" * into one array. Everything outside them is escaped.\n")
	b.WriteString(" */\n")
	b.WriteString("export const GO_PRINT_RANGES: readonly number[] = [\n")
	line := " "
	for _, r := range goPrintRanges() {
		field := " " + strconv.Itoa(int(r)) + ","
		if len(line)+len(field) > 100 {
			b.WriteString(line + "\n")
			line = " "
		}
		line += field
	}
	b.WriteString(line + "\n];\n")
	return b.String()
}
