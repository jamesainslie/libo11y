// Where the generated C11 spec header lands.
const cSpecHeaderPath = "c/include/o11y/spec.h"

var (
	cMacroPattern = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)
	errCName      = errors.New("c name")
)

// cMacroName converts a dotted, snake or kebab name to SCREAMING_SNAKE_CASE,
// dropping an o11y. prefix.
func cMacroName(name string) string {
	return rustConstName(name)
}

// cQuote renders s as an ISO C11 string literal. Printable ASCII stays as is
// (except quote, backslash, and trigraph-forming '?' sequences); all other
// bytes use 3-digit octal escapes so following hex digits are never consumed.
func cQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case '?':
			// Avoid C trigraphs like "??/" in strict C11 mode.
			if i+1 < len(s) && s[i+1] == '?' {
				b.WriteString(`\?`)
			} else {
				b.WriteByte('?')
			}
		default:
			if c >= 0x20 && c <= 0x7e {
				b.WriteByte(c)
			} else {
				fmt.Fprintf(&b, `\%03o`, c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// cCommentSafe reports whether s can be placed inside a single-line C /* */ or // comment.
func cCommentSafe(s string) bool {
	return s != "" && !strings.ContainsAny(s, "\r\n") && !strings.Contains(s, "*/")
}

// genCSpec renders c/include/o11y/spec.h: pure ISO C11 header with spec
// identity constants, closed-enum string constants, attribute key constants,
// registered event names, registered metric names, and sensitivity/cardinality
// enums matching the spec registry.
func genCSpec(m *model) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "/* Code generated by specgen from spec/registry (spec %s). DO NOT EDIT. */\n\n", m.specVersion)
	b.WriteString("#ifndef O11Y_SPEC_H\n")
	b.WriteString("#define O11Y_SPEC_H\n\n")
	b.WriteString("#include <stddef.h>\n\n")
	b.WriteString("#ifdef __cplusplus\n")
	b.WriteString("extern \"C\" {\n")
	b.WriteString("#endif\n\n")

	seen := map[string]string{}
	defineStr := func(macro, value, comment string) error {
		if !cMacroPattern.MatchString(macro) {
			return fmt.Errorf("%w: %q is not a valid C macro identifier", errCName, macro)
		}
		if prev, dup := seen[macro]; dup {
			return fmt.Errorf("%w: %s and %s both produce macro %s", errCName, prev, value, macro)
		}
		seen[macro] = value
		if comment != "" && cCommentSafe(comment) {
			fmt.Fprintf(&b, "/* %s */\n", comment)
		}
		fmt.Fprintf(&b, "#define %s %s\n", macro, cQuote(value))
		return nil
	}

	b.WriteString("/* Spec identity */\n")
	for _, item := range []struct{ macro, val, doc string }{
		{"O11Y_SCHEMA_URL", m.schemaURL, "The schema URL stamped on every resource libo11y builds."},
		{"O11Y_SPEC_VERSION", m.specVersion, "The libo11y specification version this header implements."},
		{"O11Y_SEMCONV_VERSION", m.semconvVersion, "The pinned OpenTelemetry semantic conventions version."},
		{"O11Y_EVENT_NAME_KEY", "event.name", "The log attribute that carries an event's name."},
		{"O11Y_APP_REGISTRY_SCHEMA", appregistry.SchemaV1, "The schema version declared by application attribute registries."},
	} {
		if err := defineStr(item.macro, item.val, item.doc); err != nil {
			return "", err
		}
	}

	b.WriteString("\n/* Sensitivity classification. Zero value is unclassified. */\n")
	b.WriteString("typedef enum o11y_sensitivity {\n")
	b.WriteString("    O11Y_SENSITIVITY_UNCLASSIFIED = 0,\n")
	b.WriteString("    O11Y_SENSITIVITY_PUBLIC = 1,\n")
	b.WriteString("    O11Y_SENSITIVITY_INTERNAL = 2,\n")
	b.WriteString("    O11Y_SENSITIVITY_PII = 3,\n")
	b.WriteString("    O11Y_SENSITIVITY_SECRET = 4\n")
	b.WriteString("} o11y_sensitivity_t;\n")

	b.WriteString("\n/* Cardinality budget classification. Zero value is unclassified. */\n")
	b.WriteString("typedef enum o11y_cardinality {\n")
	b.WriteString("    O11Y_CARDINALITY_UNCLASSIFIED = 0,\n")
	b.WriteString("    O11Y_CARDINALITY_ENUM = 1,\n")
	b.WriteString("    O11Y_CARDINALITY_BOUNDED = 2,\n")
	b.WriteString("    O11Y_CARDINALITY_UNBOUNDED = 3\n")
	b.WriteString("} o11y_cardinality_t;\n")

	// Closed enums: every minted enum attribute, then Environment.
	type cEnum struct {
		prefix  string
		key     string
		members []enumMember
	}
	var enums []cEnum
	for _, a := range m.minted {
		if members := a.enumMembers(); len(members) > 0 {
			enums = append(enums, cEnum{prefix: cMacroName(a.ID), key: a.ID, members: members})
		}
	}
	if env := m.environmentValues(); len(env) > 0 {
		members := make([]enumMember, len(env))
		for i, v := range env {
			members[i] = enumMember{ID: v, Value: v}
		}
		enums = append(enums, cEnum{prefix: "ENVIRONMENT", key: environmentKey, members: members})
	}

	for _, e := range enums {
		fmt.Fprintf(&b, "\n/* Closed value set for %s */\n", e.key)
		if err := defineStr("O11Y_"+e.prefix+"_KEY", e.key, ""); err != nil {
			return "", err
		}
		for _, member := range e.members {
			memberName := cMacroName(member.ID)
			doc := strings.TrimSpace(member.Brief)
			if err := defineStr("O11Y_"+e.prefix+"_"+memberName, member.Value, doc); err != nil {
				return "", err
			}
		}
	}

	b.WriteString("\n/* Attribute keys minted by the libo11y specification */\n")
	for _, a := range m.minted {
		if err := defineStr("O11Y_ATTR_"+cMacroName(a.ID), a.ID, ""); err != nil {
			return "", err
		}
	}

	copied := m.copiedRefs()
	if len(copied) > 0 {
		b.WriteString("\n/* Upstream attribute keys copied from the pinned registry snapshot */\n")
		for _, ref := range copied {
			if err := defineStr("O11Y_ATTR_"+cMacroName(ref), ref, ""); err != nil {
				return "", err
			}
		}
	}

	if len(m.events) > 0 {
		b.WriteString("\n/* Registered event names */\n")
		for _, ev := range m.events {
			if err := defineStr("O11Y_EVENT_"+cMacroName(ev.Name), ev.Name, ""); err != nil {
				return "", err
			}
		}
	}

	if len(m.metrics) > 0 {
		b.WriteString("\n/* Registered metric names */\n")
		for _, mt := range m.metrics {
			if err := defineStr("O11Y_METRIC_"+cMacroName(mt.MetricName), mt.MetricName, ""); err != nil {
				return "", err
			}
		}
	}

	b.WriteString("\n#ifdef __cplusplus\n")
	b.WriteString("} /* extern \"C\" */\n")
	b.WriteString("#endif\n\n")
	b.WriteString("#endif /* O11Y_SPEC_H */\n")
	return b.String(), nil
}
