// genPyTables renders tables.py with immutable MappingProxyType tables, tuples,
// and frozensets matching the Go, TypeScript, Rust, and Zig tables.
func genPyTables(m *model) (string, error) {
	var b strings.Builder
	pyHeader(&b, m)
	b.WriteString(pyTablesPreamble)

	b.WriteString("\n\nRESOURCE: Final[Mapping[str, ResourceAttr]] = MappingProxyType(\n    {\n")
	for _, tier := range m.tierOrder {
		for _, a := range m.tiers[tier] {
			fmt.Fprintf(&b, "        %s: ResourceAttr(\n", pyQuote(a.name()))
			fmt.Fprintf(&b, "            key=%s,\n", pyQuote(a.name()))
			fmt.Fprintf(&b, "            tier=%s,\n", pyQuote(tier))
			fmt.Fprintf(&b, "            requirement=%s,\n", pyRequirement(a.requirement()))
			fmt.Fprintf(&b, "            source=%s,\n", pyQuote(a.Annotations["o11y.source"]))
			fmt.Fprintf(&b, "            role=%s,\n", pyQuote(a.Annotations["o11y.role"]))
			b.WriteString("        ),\n")
		}
	}
	b.WriteString("    }\n)\n")

	var tier0 []string
	for _, a := range m.tiers["tier0"] {
		if a.requirement() == "required" {
			tier0 = append(tier0, a.name())
		}
	}
	head := "REQUIRED_TIER0: Final[tuple[str, ...]] = "
	b.WriteString("\n" + head + pyTuple(pyQuoteAll(tier0), 0, utf8.RuneCountInString(head), 0) + "\n")

	head = "ENVIRONMENT_VALUES: Final[frozenset[str]] = "
	b.WriteString("\n" + head + pyFrozenSet(pyQuoteAll(m.environmentValues()), 0, utf8.RuneCountInString(head)) + "\n")

	b.WriteString("\nSENSITIVITY_OF: Final[Mapping[str, Sensitivity]] = MappingProxyType(\n    {\n")
	for _, name := range slices.Sorted(maps.Keys(m.classByName)) {
		cls, err := pySensitivity(m.classByName[name])
		if err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "        %s: %s,\n", pyQuote(name), cls)
	}
	b.WriteString("    }\n)\n")

	b.WriteString("\nCARDINALITY_OF: Final[Mapping[str, Cardinality]] = MappingProxyType(\n    {\n")
	for _, name := range slices.Sorted(maps.Keys(m.cardByName)) {
		card, err := pyCardinality(m.cardByName[name])
		if err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "        %s: %s,\n", pyQuote(name), card)
	}
	b.WriteString("    }\n)\n")

	b.WriteString("\nLEGACY_KEYS: Final[Mapping[str, str]] = MappingProxyType(\n    {\n")
	for _, name := range slices.Sorted(maps.Keys(m.legacyKeys)) {
		fmt.Fprintf(&b, "        %s: %s,\n", pyQuote(name), pyQuote(m.legacyKeys[name]))
	}
	b.WriteString("    }\n)\n")

	labels := make([]string, len(m.metricLabels))
	for i, a := range m.metricLabels {
		labels[i] = a.name()
	}
	head = "METRIC_RESOURCE_LABELS: Final[tuple[str, ...]] = "
	b.WriteString("\n" + head + pyTuple(pyQuoteAll(labels), 0, utf8.RuneCountInString(head), 0) + "\n")

	b.WriteString("\nEVENTS: Final[Mapping[str, EventInfo]] = MappingProxyType(\n    {\n")
	for _, ev := range m.events {
		required, templates := m.eventRequirements(ev)
		fmt.Fprintf(&b, "        %s: EventInfo(\n", pyQuote(ev.Name))
		fmt.Fprintf(&b, "            name=%s,\n", pyQuote(ev.Name))
		reqHead := "            required="
		fmt.Fprintf(&b, "%s%s,\n", reqHead, pyTuple(pyQuoteAll(required), 3, utf8.RuneCountInString(reqHead), 1))
		tplHead := "            required_templates="
		fmt.Fprintf(&b, "%s%s,\n", tplHead, pyTuple(pyQuoteAll(templates), 3, utf8.RuneCountInString(tplHead), 1))
		b.WriteString("        ),\n")
	}
	b.WriteString("    }\n)\n")

	b.WriteString("\nMETRICS: Final[Mapping[str, MetricInfo]] = MappingProxyType(\n    {\n")
	for _, mt := range m.metrics {
		inst, err := pyInstrument(mt.Instrument)
		if err != nil {
			return "", fmt.Errorf("metric %s: %w", mt.MetricName, err)
		}
		fmt.Fprintf(&b, "        %s: MetricInfo(\n", pyQuote(mt.MetricName))
		fmt.Fprintf(&b, "            name=%s,\n", pyQuote(mt.MetricName))
		fmt.Fprintf(&b, "            instrument=%s,\n", inst)
		fmt.Fprintf(&b, "            unit=%s,\n", pyQuote(mt.Unit))
		b.WriteString("        ),\n")
	}
	b.WriteString("    }\n)\n")

	writeSpanMap := func(varName string, groups []group, ann string) {
		fmt.Fprintf(&b, "\n%s: Final[Mapping[str, tuple[str, ...]]] = MappingProxyType(\n    {\n", varName)
		for _, g := range groups {
			key := pyQuote(g.Annotations[ann])
			entryHead := "        " + key + ": "
			b.WriteString(entryHead + pyTuple(pyQuoteAll(requiredNames(g)), 2, utf8.RuneCountInString(entryHead), 1) + ",\n")
		}
		b.WriteString("    }\n)\n")
	}

	writeSpanMap("SPAN_REQUIRED", m.spans, "o11y.span.kind")
	writeSpanMap("RUM_SPAN_REQUIRED", m.rumSpans, "o11y.rum.span")

	fmt.Fprintf(&b, "\nAPP_REGISTRY_SCHEMA: Final[str] = %s\n", pyQuote(appregistry.SchemaV1))
	head = "APP_RESERVED_NAMESPACES: Final[frozenset[str]] = "
	b.WriteString("\n" + head + pyFrozenSet(pyQuoteAll(appregistry.ReservedNamespaces()), 0, utf8.RuneCountInString(head)) + "\n")

	return b.String(), nil
}

// genPyGoPrint renders goprint.py: the goPrintRanges bounds as a tuple of
// flattened inclusive [lo, hi] integers, formatted to match ruff format.
func genPyGoPrint() string {
	ranges := goPrintRanges()
	var b strings.Builder
	b.WriteString("# Code generated by specgen from Go's unicode.IsPrint (Unicode " + unicode.Version + "). DO NOT EDIT.\n\n")
	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString("from typing import Final\n\n")
	b.WriteString("GO_PRINT_RANGES: Final[tuple[int, ...]] = (\n")
	for i := 0; i+1 < len(ranges); i += 2 {
		fmt.Fprintf(&b, "%s%s,\n%s%s,\n", pyIndent, strconv.Itoa(int(ranges[i])), pyIndent, strconv.Itoa(int(ranges[i+1])))
	}
	b.WriteString(")\n")
	return b.String()
}
