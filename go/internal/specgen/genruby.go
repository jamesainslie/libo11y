// Where the Ruby artifacts land, inside ruby/lib/libo11y/spec/generated.
const (
	rbSpecPath    = "ruby/lib/libo11y/spec/generated/spec.rb"
	rbTablesPath  = "ruby/lib/libo11y/spec/generated/tables.rb"
	rbGoPrintPath = "ruby/lib/libo11y/spec/generated/goprint.rb"
)

// rbReservedTypes are module/class names a generated enum may not take.
var rbReservedTypes = map[string]bool{
	"Tables": true, "GoPrint": true, "AppRegistry": true,
	"GoQuote": true, "YamlV3": true,
	"Sensitivity": true, "Cardinality": true, "Requirement": true,
	"Instrument": true, "ResourceAttr": true, "EventInfo": true,
	"MetricInfo": true, "Environment": true,
}

var (
	rbConstPattern = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)
	rbTypePattern  = regexp.MustCompile(`^[A-Z][A-Za-z0-9_]*$`)
)

// errRbName reports a registry name the Ruby gem cannot carry.
var errRbName = errors.New("ruby name")

// rbConstName converts a dotted, snake or kebab name to SCREAMING_SNAKE_CASE,
// dropping an o11y. prefix.
func rbConstName(name string) string {
	return strings.ToUpper(strings.Join(rustSegments(strings.TrimPrefix(name, "o11y.")), "_"))
}

// rbQuote renders s as a double-quoted Ruby string literal.
func rbQuote(s string) string {
	raw, _ := json.Marshal(s)
	// Escape Ruby interpolation sequence "#{" or "#@" or "#$" if present.
	escaped := strings.ReplaceAll(string(raw), "#{", `\#{`)
	escaped = strings.ReplaceAll(escaped, "#@", `\#@`)
	escaped = strings.ReplaceAll(escaped, "#$", `\#$`)
	return escaped
}

func rbQuoteAll(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = rbQuote(n)
	}
	return out
}

func rbHeader(b *strings.Builder, m *model) {
	b.WriteString("# frozen_string_literal: true\n\n")
	fmt.Fprintf(b, "# Code generated by specgen from spec/registry (spec %s). DO NOT EDIT.\n\n", m.specVersion)
}

type rbEnum struct {
	typeName string
	key      string
	members  []enumMember
	names    []string
}

func (m *model) rbEnums() ([]rbEnum, error) {
	var enums []rbEnum
	for _, a := range m.minted {
		if members := a.enumMembers(); len(members) > 0 {
			enums = append(enums, rbEnum{typeName: goName(a.ID), key: a.ID, members: members})
		}
	}
	if env := m.environmentValues(); len(env) > 0 {
		members := make([]enumMember, len(env))
		for i, v := range env {
			members[i] = enumMember{ID: v, Value: v}
		}
		enums = append(enums, rbEnum{typeName: "Environment", key: environmentKey, members: members})
	}
	types := map[string]string{}
	for i, e := range enums {
		if !rbTypePattern.MatchString(e.typeName) {
			return nil, fmt.Errorf("%w: attribute %s: %q is not a Ruby module name", errRbName, e.key, e.typeName)
		}
		if other, dup := types[e.typeName]; dup {
			return nil, fmt.Errorf("%w: attributes %s and %s both become enum %s", errRbName, other, e.key, e.typeName)
		}
		if rbReservedTypes[e.typeName] && e.key != environmentKey {
			return nil, fmt.Errorf("%w: attribute %s: enum %s would collide with a spec module", errRbName, e.key, e.typeName)
		}
		types[e.typeName] = e.key
		seen := map[string]string{}
		for _, member := range e.members {
			name := rbConstName(member.ID)
			if !rbConstPattern.MatchString(name) || name == "ALL" {
				return nil, fmt.Errorf("%w: attribute %s: member %s: %q is not a Ruby constant name", errRbName, e.key, member.ID, name)
			}
			if other, dup := seen[name]; dup {
				return nil, fmt.Errorf("%w: attribute %s: members %s and %s both become %s", errRbName, e.key, other, member.ID, name)
			}
			seen[name] = member.ID
			enums[i].names = append(enums[i].names, name)
		}
	}
	return enums, nil
}

// genRbSpec renders ruby/lib/libo11y/spec/generated/spec.rb.
func genRbSpec(m *model) (string, error) {
	enums, err := m.rbEnums()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	rbHeader(&b, m)
	b.WriteString("module Libo11y\n  module Spec\n")
	fmt.Fprintf(&b, "    SCHEMA_URL = %s\n", rbQuote(m.schemaURL))
	fmt.Fprintf(&b, "    SPEC_VERSION = %s\n", rbQuote(m.specVersion))
	fmt.Fprintf(&b, "    SEMCONV_VERSION = %s\n", rbQuote(m.semconvVersion))
	fmt.Fprintf(&b, "    EVENT_NAME_KEY = %s\n", rbQuote("event.name"))

	for _, e := range enums {
		fmt.Fprintf(&b, "\n    module %s\n", e.typeName)
		for i, member := range e.members {
			fmt.Fprintf(&b, "      %s = %s\n", e.names[i], rbQuote(member.Value))
		}
		fmt.Fprintf(&b, "      ALL = [%s].freeze\n", strings.Join(e.names, ", "))
		b.WriteString("      def self.valid?(value)\n        ALL.include?(value)\n      end\n")
		b.WriteString("    end\n")
	}

	seen := map[string]string{}
	writeConst := func(prefix, raw string) error {
		name := prefix + rbConstName(raw)
		if !rbConstPattern.MatchString(name) {
			return fmt.Errorf("%w: %s: %q is not a Ruby constant name", errRbName, raw, name)
		}
		if other, dup := seen[name]; dup {
			return fmt.Errorf("%w: %s and %s both become constant %s", errRbName, other, raw, name)
		}
		seen[name] = raw
		fmt.Fprintf(&b, "    %s = %s\n", name, rbQuote(raw))
		return nil
	}

	b.WriteString("\n    # Attribute keys minted by the libo11y specification.\n")
	for _, a := range m.minted {
		if err := writeConst("ATTR_", a.ID); err != nil {
			return "", err
		}
	}
	if copied := m.copiedRefs(); len(copied) > 0 {
		b.WriteString("\n    # Upstream attribute keys copied from the pinned registry snapshot.\n")
		for _, name := range copied {
			if err := writeConst("ATTR_", name); err != nil {
				return "", err
			}
		}
	}
	b.WriteString("\n    # Registered event names.\n")
	for _, ev := range m.events {
		if err := writeConst("EVENT_", ev.Name); err != nil {
			return "", err
		}
	}
	if len(m.metrics) > 0 {
		b.WriteString("\n    # Registered metric names.\n")
		for _, mt := range m.metrics {
			if err := writeConst("METRIC_", mt.MetricName); err != nil {
				return "", err
			}
		}
	}
	b.WriteString("  end\nend\n")
	return b.String(), nil
}

func rbRequirement(level string) string {
	switch level {
	case "required":
		return "Requirement::REQUIRED"
	case "conditionally_required":
		return "Requirement::CONDITIONALLY_REQUIRED"
	case "opt_in":
		return "Requirement::OPT_IN"
	default:
		return "Requirement::RECOMMENDED"
	}
}

func rbSensitivity(class string) (string, error) {
	if _, err := sensitivityConst(class); err != nil {
		return "", err
	}
	return "Sensitivity::" + strings.ToUpper(class), nil
}

func rbCardinality(class string) (string, error) {
	switch class {
	case "enum":
		return "Cardinality::ENUM", nil
	case "bounded":
		return "Cardinality::BOUNDED", nil
	case "unbounded":
		return "Cardinality::UNBOUNDED", nil
	default:
		return "", fmt.Errorf("unknown cardinality class %q", class)
	}
}

func rbInstrument(instrument string) (string, error) {
	switch instrument {
	case "counter":
		return "Instrument::COUNTER", nil
	case "histogram":
		return "Instrument::HISTOGRAM", nil
	case "gauge":
		return "Instrument::GAUGE", nil
	case "updowncounter":
		return "Instrument::UP_DOWN_COUNTER", nil
	default:
		return "", fmt.Errorf("unknown instrument %q", instrument)
	}
}

const rbTablesPreamble = `require "set"

module Libo11y
  module Spec
    module Sensitivity
      PUBLIC = "public"
      INTERNAL = "internal"
      PII = "pii"
      SECRET = "secret"
      ALL = [PUBLIC, INTERNAL, PII, SECRET].freeze
    end

    module Cardinality
      ENUM = "enum"
      BOUNDED = "bounded"
      UNBOUNDED = "unbounded"
      ALL = [ENUM, BOUNDED, UNBOUNDED].freeze
    end

    module Requirement
      REQUIRED = "required"
      CONDITIONALLY_REQUIRED = "conditionally_required"
      RECOMMENDED = "recommended"
      OPT_IN = "opt_in"
      ALL = [REQUIRED, CONDITIONALLY_REQUIRED, RECOMMENDED, OPT_IN].freeze
    end

    module Instrument
      COUNTER = "counter"
      HISTOGRAM = "histogram"
      GAUGE = "gauge"
      UP_DOWN_COUNTER = "updowncounter"
      ALL = [COUNTER, HISTOGRAM, GAUGE, UP_DOWN_COUNTER].freeze
    end

    ResourceAttr = Data.define(:key, :tier, :requirement, :source, :role)
    EventInfo = Data.define(:name, :required, :required_templates)
    MetricInfo = Data.define(:name, :instrument, :unit)
`

func rbStringArray(items []string) string {
	if len(items) == 0 {
		return "[].freeze"
	}
	return "[" + strings.Join(rbQuoteAll(items), ", ") + "].freeze"
}

// genRbTables renders ruby/lib/libo11y/spec/generated/tables.rb.
func genRbTables(m *model) (string, error) {
	var b strings.Builder
	rbHeader(&b, m)
	b.WriteString(rbTablesPreamble)

	b.WriteString("\n    RESOURCE = {\n")
	for _, tier := range m.tierOrder {
		for _, a := range m.tiers[tier] {
			fmt.Fprintf(&b, "      %s => ResourceAttr.new(\n", rbQuote(a.name()))
			fmt.Fprintf(&b, "        key: %s,\n", rbQuote(a.name()))
			fmt.Fprintf(&b, "        tier: %s,\n", rbQuote(tier))
			fmt.Fprintf(&b, "        requirement: %s,\n", rbRequirement(a.requirement()))
			fmt.Fprintf(&b, "        source: %s,\n", rbQuote(a.Annotations["o11y.source"]))
			fmt.Fprintf(&b, "        role: %s\n", rbQuote(a.Annotations["o11y.role"]))
			b.WriteString("      ),\n")
		}
	}
	b.WriteString("    }.freeze\n")

	var tier0 []string
	for _, a := range m.tiers["tier0"] {
		if a.requirement() == "required" {
			tier0 = append(tier0, a.name())
		}
	}
	fmt.Fprintf(&b, "\n    REQUIRED_TIER0 = %s\n", rbStringArray(tier0))
	fmt.Fprintf(&b, "\n    ENVIRONMENT_VALUES = Set[%s].freeze\n", strings.Join(rbQuoteAll(m.environmentValues()), ", "))

	b.WriteString("\n    SENSITIVITY_OF = {\n")
	for _, name := range slices.Sorted(maps.Keys(m.classByName)) {
		cls, err := rbSensitivity(m.classByName[name])
		if err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "      %s => %s,\n", rbQuote(name), cls)
	}
	b.WriteString("    }.freeze\n")

	b.WriteString("\n    CARDINALITY_OF = {\n")
	for _, name := range slices.Sorted(maps.Keys(m.cardByName)) {
		card, err := rbCardinality(m.cardByName[name])
		if err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "      %s => %s,\n", rbQuote(name), card)
	}
	b.WriteString("    }.freeze\n")

	b.WriteString("\n    LEGACY_KEYS = {\n")
	for _, name := range slices.Sorted(maps.Keys(m.legacyKeys)) {
		fmt.Fprintf(&b, "      %s => %s,\n", rbQuote(name), rbQuote(m.legacyKeys[name]))
	}
	b.WriteString("    }.freeze\n")

	labels := make([]string, len(m.metricLabels))
	for i, a := range m.metricLabels {
		labels[i] = a.name()
	}
	fmt.Fprintf(&b, "\n    METRIC_RESOURCE_LABELS = %s\n", rbStringArray(labels))

	b.WriteString("\n    EVENTS = {\n")
	for _, ev := range m.events {
		required, templates := m.eventRequirements(ev)
		fmt.Fprintf(&b, "      %s => EventInfo.new(\n", rbQuote(ev.Name))
		fmt.Fprintf(&b, "        name: %s,\n", rbQuote(ev.Name))
		fmt.Fprintf(&b, "        required: %s,\n", rbStringArray(required))
		fmt.Fprintf(&b, "        required_templates: %s\n", rbStringArray(templates))
		b.WriteString("      ),\n")
	}
	b.WriteString("    }.freeze\n")

	b.WriteString("\n    METRICS = {\n")
	for _, mt := range m.metrics {
		inst, err := rbInstrument(mt.Instrument)
		if err != nil {
			return "", fmt.Errorf("metric %s: %w", mt.MetricName, err)
		}
		fmt.Fprintf(&b, "      %s => MetricInfo.new(\n", rbQuote(mt.MetricName))
		fmt.Fprintf(&b, "        name: %s,\n", rbQuote(mt.MetricName))
		fmt.Fprintf(&b, "        instrument: %s,\n", inst)
		fmt.Fprintf(&b, "        unit: %s\n", rbQuote(mt.Unit))
		b.WriteString("      ),\n")
	}
	b.WriteString("    }.freeze\n")

	writeSpanMap := func(varName string, groups []group, ann string) {
		fmt.Fprintf(&b, "\n    %s = {\n", varName)
		for _, g := range groups {
			fmt.Fprintf(&b, "      %s => %s,\n", rbQuote(g.Annotations[ann]), rbStringArray(requiredNames(g)))
		}
		b.WriteString("    }.freeze\n")
	}

	writeSpanMap("SPAN_REQUIRED", m.spans, "o11y.span.kind")
	writeSpanMap("RUM_SPAN_REQUIRED", m.rumSpans, "o11y.rum.span")

	fmt.Fprintf(&b, "\n    APP_REGISTRY_SCHEMA = %s\n", rbQuote(appregistry.SchemaV1))
	reserved := appregistry.ReservedNamespaces()
	b.WriteString("\n    APP_RESERVED_NAMESPACES = Set[\n")
	for _, ns := range reserved {
		fmt.Fprintf(&b, "      %s,\n", rbQuote(ns))
	}
	b.WriteString("    ].freeze\n")
	b.WriteString("  end\nend\n")
	return b.String(), nil
}

// genRbGoPrint renders ruby/lib/libo11y/spec/generated/goprint.rb.
func genRbGoPrint() string {
	ranges := goPrintRanges()
	var b strings.Builder
	b.WriteString("# frozen_string_literal: true\n\n")
	b.WriteString("# Code generated by specgen from Go's unicode.IsPrint (Unicode " + unicode.Version + "). DO NOT EDIT.\n\n")
	b.WriteString("module Libo11y\n  module Spec\n    GO_PRINT_RANGES = [\n")
	for i := 0; i+1 < len(ranges); i += 2 {
		fmt.Fprintf(&b, "      %s, %s,\n", strconv.Itoa(int(ranges[i])), strconv.Itoa(int(ranges[i+1])))
	}
	b.WriteString("    ].freeze\n  end\nend\n")
	return b.String()
}
