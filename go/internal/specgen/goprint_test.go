// inRanges reports whether r lies in one of the sorted, inclusive
// [lo, hi] pairs.
func inRanges(ranges []rune, r rune) bool {
	i, _ := slices.BinarySearch(ranges, r)
	// ranges[i] is the first bound >= r. r is inside a pair when that bound
	// is a hi (odd index) or is the lo it equals.
	return i < len(ranges) && (i%2 == 1 || ranges[i] == r)
}

func TestGoPrintRangesMatchIsPrint(t *testing.T) {
	ranges := goPrintRanges()
	if len(ranges) == 0 || len(ranges)%2 != 0 {
		t.Fatalf("got %d bounds, want a non-empty even count", len(ranges))
	}
	for i := 1; i < len(ranges); i++ {
		// Each pair is ordered, and pairs neither overlap nor touch, so the
		// encoding is the shortest one.
		if i%2 == 1 && ranges[i] < ranges[i-1] || i%2 == 0 && ranges[i] <= ranges[i-1]+1 {
			t.Fatalf("bounds %d and %d (%#x, %#x) are out of order", i-1, i, ranges[i-1], ranges[i])
		}
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if got, want := inRanges(ranges, r), unicode.IsPrint(r); got != want {
			t.Fatalf("U+%04X: in ranges %v, unicode.IsPrint %v", r, got, want)
		}
	}
}

func TestTypeScriptGoPrintGenerated(t *testing.T) {
	src := genTSGoPrint()
	header := "// Code generated by specgen from Go's unicode.IsPrint (Unicode " + unicode.Version + "). DO NOT EDIT.\n"
	if !strings.HasPrefix(src, header) {
		t.Fatalf("header: got %q", src[:min(len(src), len(header))])
	}
	const decl = "export const GO_PRINT_RANGES: readonly number[] = ["
	start := strings.Index(src, decl)
	end := strings.LastIndex(src, "];")
	if start < 0 || end < start {
		t.Fatalf("no %q array in:\n%s", decl, src)
	}
	var got []rune
	for _, field := range strings.FieldsFunc(src[start+len(decl):end], func(r rune) bool { return r == ',' || unicode.IsSpace(r) }) {
		n, err := strconv.ParseInt(field, 10, 32)
		if err != nil {
			t.Fatalf("bound %q: %v", field, err)
		}
		got = append(got, rune(n))
	}
	if !slices.Equal(got, goPrintRanges()) {
		t.Fatalf("the generated array does not round-trip goPrintRanges: %d bounds, want %d", len(got), len(goPrintRanges()))
	}
	for line := range strings.SplitSeq(src, "\n") {
		if len(line) > 110 {
			t.Fatalf("line longer than 110 columns: %q", line)
		}
	}
}

func TestRenderWritesGoPrint(t *testing.T) {
	m, err := load(writeRegistry(t, map[string]string{"a.yaml": tsFixture}))
	if err != nil {
		t.Fatal(err)
	}
	outputs, err := render(m)
	if err != nil {
		t.Fatal(err)
	}
	if outputs[tsGoPrintPath] != genTSGoPrint() {
		t.Fatalf("render does not write %s", tsGoPrintPath)
	}
}
