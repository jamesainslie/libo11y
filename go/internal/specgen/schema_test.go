package main

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"

	schema "go.opentelemetry.io/otel/schema/v1.1"

	"github.com/jamesainslie/libo11y/go/spec"
)

const wantSchemaURL = "https://jamesainslie.dev/schemas/libo11y/1.0.0"

// TestSchemaArtifactIsValidAndConsistent pins the schema contract: the
// manifest, the generated spec package, and the committed OpenTelemetry
// schema file all name the same schema URL, and the file parses with the
// upstream schema parser.
func TestSchemaArtifactIsValidAndConsistent(t *testing.T) {
	if spec.SchemaURL != wantSchemaURL {
		t.Fatalf("spec.SchemaURL = %q, want %q", spec.SchemaURL, wantSchemaURL)
	}
	m, err := load("../../..")
	if err != nil {
		t.Fatal(err)
	}
	if m.schemaURL != wantSchemaURL || m.specVersion != "1.0.0" {
		t.Fatalf("manifest schema_url = %q (version %q), want %q", m.schemaURL, m.specVersion, wantSchemaURL)
	}
	path := filepath.Join("../../..", "spec", "schemas", m.specVersion)
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("schema artifact missing: %v", err)
	}
	parsed, err := schema.Parse(bytes.NewReader(raw))
	if err != nil {
		t.Fatalf("schema file does not parse as an OpenTelemetry schema: %v", err)
	}
	if parsed.SchemaURL != m.schemaURL {
		t.Errorf("schema file schema_url = %q, want %q", parsed.SchemaURL, m.schemaURL)
	}
	if _, ok := parsed.Versions["1.0.0"]; !ok {
		t.Errorf("schema file lacks version 1.0.0: %v", parsed.Versions)
	}
}

// TestManifestRejectsSchemaURLWithExtension pins that the manifest's
// schema_url is an absolute URL ending in a bare semantic version, which
// load uses as the spec version and the schema file name.
func TestManifestRejectsSchemaURLWithExtension(t *testing.T) {
	for _, url := range []string{
		"https://jamesainslie.dev/schemas/libo11y/1.0.0.yaml",
		"https://jamesainslie.dev/schemas/libo11y/v1.0.0",
		"https://jamesainslie.dev/schemas/libo11y/1.0",
		"https://jamesainslie.dev/schemas/libo11y/01.0.0",
		"https://jamesainslie.dev/schemas/libo11y/",
		"jamesainslie.dev/schemas/libo11y/1.0.0",
		"ftp://jamesainslie.dev/schemas/libo11y/1.0.0",
		"",
	} {
		t.Run(url, func(t *testing.T) {
			root := writeManifest(t, url)
			if _, err := load(root); !errors.Is(err, errSchemaURL) {
				t.Errorf("load error = %v, want %v", err, errSchemaURL)
			}
		})
	}
}

// TestManifestAcceptsVersionedSchemaURL is the positive counterpart: any
// absolute http(s) URL ending in a bare semantic version loads, and its last
// segment becomes the spec version.
func TestManifestAcceptsVersionedSchemaURL(t *testing.T) {
	for url, version := range map[string]string{
		"https://jamesainslie.dev/schemas/libo11y/1.0.0": "1.0.0",
		"https://example.com/s/2.10.3":                   "2.10.3",
		"http://example.com/0.1.0":                       "0.1.0",
	} {
		t.Run(url, func(t *testing.T) {
			m, err := load(writeManifest(t, url))
			if err != nil {
				t.Fatalf("load: %v", err)
			}
			if m.specVersion != version {
				t.Errorf("specVersion = %q, want %q", m.specVersion, version)
			}
		})
	}
}

// TestSchemaRenderingRefusesLaterVersions pins that the generator refuses
// a version after 1.0.0 until it models the version history: a later
// schema file must list every earlier version and its transformations, and
// rendering only the current node would silently drop them.
func TestSchemaRenderingRefusesLaterVersions(t *testing.T) {
	m, err := load(writeManifest(t, "https://jamesainslie.dev/schemas/libo11y/1.1.0"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := render(m); err == nil || !strings.Contains(err.Error(), "1.1.0") {
		t.Errorf("render error = %v, want a refusal naming 1.1.0", err)
	}
}

// TestNoStaleSchemaFiles pins that every file under spec/schemas is one the
// generator renders, so a stale or hand-written schema file fails go test.
func TestNoStaleSchemaFiles(t *testing.T) {
	root := "../../.."
	m, err := load(root)
	if err != nil {
		t.Fatal(err)
	}
	outputs, err := render(m)
	if err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(filepath.Join(root, "spec", "schemas"))
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if _, ok := outputs["spec/schemas/"+e.Name()]; !ok {
			t.Errorf("spec/schemas/%s is not generated by specgen", e.Name())
		}
	}
}

// writeManifest builds an empty registry whose manifest carries schemaURL.
func writeManifest(t *testing.T, schemaURL string) string {
	t.Helper()
	root := writeRegistry(t, nil)
	manifest := filepath.Join(root, "spec", "registry", "manifest.yaml")
	body := "name: t\nschema_url: \"" + schemaURL + "\"\nsemconv_version: 1.41.0\n"
	if err := os.WriteFile(manifest, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return root
}
