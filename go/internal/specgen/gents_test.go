package main

import (
	"strings"
	"testing"
)

const tsFixture = `
groups:
  - id: registry.o11y
    type: attribute_group
    attributes:
      - id: o11y.outcome
        type:
          members:
            - {id: success, value: "success"}
            - {id: needs_review, value: "needs-review"}
        annotations: {o11y.sensitivity: public, o11y.cardinality: enum}
      - id: o11y.tenant.id
        type: string
        annotations: {o11y.sensitivity: internal, o11y.cardinality: bounded}
  - id: event.o11y.thing.happened
    type: event
    name: o11y.thing.happened
    stability: development
    attributes:
      - ref: o11y.outcome
        requirement_level: required
  - id: metric.o11y.things
    type: metric
    metric_name: o11y.things
    instrument: counter
    unit: "{thing}"
    stability: development
  - id: libo11y.rum.span.view
    type: attribute_group
    annotations: {o11y.rum.span: view}
    attributes:
      - ref: o11y.tenant.id
        requirement_level: required
`

func TestTypeScriptSpecGenerated(t *testing.T) {
	m, err := load(writeRegistry(t, map[string]string{"a.yaml": tsFixture}))
	if err != nil {
		t.Fatal(err)
	}
	src := genTSSpec(m)
	for _, want := range []string{
		"// Code generated by specgen from spec/registry (spec 1.0.0). DO NOT EDIT.\n",
		`export const SPEC_VERSION = "1.0.0";`,
		`export const SCHEMA_URL = "https://schemas.o11y.ing/libo11y/1.0.0";`,
		`export type Outcome = "success" | "needs-review";`,
		`export const OUTCOME_VALUE_NEEDS_REVIEW = "needs-review";`,
		`export const OUTCOME_VALUES: readonly Outcome[] = ["success", "needs-review"];`,
		`export const ATTR_OUTCOME = "o11y.outcome";`,
		`export const ATTR_TENANT_ID = "o11y.tenant.id";`,
		`export const EVENT_THING_HAPPENED = "o11y.thing.happened";`,
		`export const METRIC_THINGS = "o11y.things";`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("genTSSpec missing %s\n%s", want, src)
		}
	}
}

