// genJavaTables renders java/libo11y-spec/src/main/java/ing/o11y/libo11y/spec/generated/SpecTables.java.
func genJavaTables(m *model) (string, error) {
	var b strings.Builder
	javaHeader(&b, m)
	b.WriteString(javaTablesPreamble)

	b.WriteString("    public static final Map<String, ResourceAttr> RESOURCE = buildResource();\n")
	var tier0 []string
	for _, a := range m.tiers["tier0"] {
		if a.requirement() == "required" {
			tier0 = append(tier0, a.name())
		}
	}
	fmt.Fprintf(&b, "    public static final List<String> REQUIRED_TIER0 = %s;\n", javaStringList(tier0))
	fmt.Fprintf(&b, "    public static final Set<String> ENVIRONMENT_VALUES = Set.copyOf(%s);\n", javaStringList(m.environmentValues()))
	b.WriteString("    public static final Map<String, Sensitivity> SENSITIVITY_OF = buildSensitivity();\n")
	b.WriteString("    public static final Map<String, Cardinality> CARDINALITY_OF = buildCardinality();\n")
	b.WriteString("    public static final Map<String, String> LEGACY_KEYS = buildLegacyKeys();\n")
	b.WriteString("    /** The registry type of every attribute that has a key in {@code Spec.Attributes}: string, boolean, int, double, enum or template[...]. */\n")
	b.WriteString("    public static final Map<String, String> ATTRIBUTE_TYPES = buildAttributeTypes();\n")

	labels := make([]string, len(m.metricLabels))
	for i, a := range m.metricLabels {
		labels[i] = a.name()
	}
	fmt.Fprintf(&b, "    public static final List<String> METRIC_RESOURCE_LABELS = %s;\n", javaStringList(labels))
	b.WriteString("    public static final Map<String, EventInfo> EVENTS = buildEvents();\n")
	b.WriteString("    public static final Map<String, MetricInfo> METRICS = buildMetrics();\n")
	b.WriteString("    public static final Map<String, List<String>> SPAN_REQUIRED = buildSpanRequired();\n")
	b.WriteString("    public static final Map<String, List<String>> RUM_SPAN_REQUIRED = buildRumSpanRequired();\n")
	fmt.Fprintf(&b, "    public static final String APP_REGISTRY_SCHEMA = %s;\n", javaQuote(appregistry.SchemaV1))
	b.WriteString("    public static final Set<String> APP_RESERVED_NAMESPACES = buildAppReservedNamespaces();\n")

	b.WriteString("\n    private static Map<String, ResourceAttr> buildResource() {\n")
	b.WriteString("        Map<String, ResourceAttr> map = new LinkedHashMap<>();\n")
	for _, tier := range m.tierOrder {
		for _, a := range m.tiers[tier] {
			fmt.Fprintf(&b, "        map.put(%s, new ResourceAttr(%s, %s, %s, %s, %s));\n",
				javaQuote(a.name()),
				javaQuote(a.name()),
				javaQuote(tier),
				javaRequirement(a.requirement()),
				javaQuote(a.Annotations["o11y.source"]),
				javaQuote(a.Annotations["o11y.role"]),
			)
		}
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	b.WriteString("\n    private static Map<String, Sensitivity> buildSensitivity() {\n")
	b.WriteString("        Map<String, Sensitivity> map = new LinkedHashMap<>();\n")
	for _, name := range slices.Sorted(maps.Keys(m.classByName)) {
		cls, err := javaSensitivity(m.classByName[name])
		if err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "        map.put(%s, %s);\n", javaQuote(name), cls)
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	b.WriteString("\n    private static Map<String, Cardinality> buildCardinality() {\n")
	b.WriteString("        Map<String, Cardinality> map = new LinkedHashMap<>();\n")
	for _, name := range slices.Sorted(maps.Keys(m.cardByName)) {
		card, err := javaCardinality(m.cardByName[name])
		if err != nil {
			return "", fmt.Errorf("attribute %s: %w", name, err)
		}
		fmt.Fprintf(&b, "        map.put(%s, %s);\n", javaQuote(name), card)
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	b.WriteString("\n    private static Map<String, String> buildLegacyKeys() {\n")
	b.WriteString("        Map<String, String> map = new LinkedHashMap<>();\n")
	for _, name := range slices.Sorted(maps.Keys(m.legacyKeys)) {
		fmt.Fprintf(&b, "        map.put(%s, %s);\n", javaQuote(name), javaQuote(m.legacyKeys[name]))
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	keys, err := m.javaKeys()
	if err != nil {
		return "", err
	}
	b.WriteString("\n    private static Map<String, String> buildAttributeTypes() {\n")
	b.WriteString("        Map<String, String> map = new LinkedHashMap<>();\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "        map.put(%s, %s);\n", javaQuote(k.name), javaQuote(k.scalar))
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	b.WriteString("\n    private static Map<String, EventInfo> buildEvents() {\n")
	b.WriteString("        Map<String, EventInfo> map = new LinkedHashMap<>();\n")
	for _, ev := range m.events {
		required, templates := m.eventRequirements(ev)
		fmt.Fprintf(&b, "        map.put(%s, new EventInfo(%s, %s, %s));\n",
			javaQuote(ev.Name),
			javaQuote(ev.Name),
			javaStringList(required),
			javaStringList(templates),
		)
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	b.WriteString("\n    private static Map<String, MetricInfo> buildMetrics() {\n")
	b.WriteString("        Map<String, MetricInfo> map = new LinkedHashMap<>();\n")
	for _, mt := range m.metrics {
		inst, err := javaInstrument(mt.Instrument)
		if err != nil {
			return "", fmt.Errorf("metric %s: %w", mt.MetricName, err)
		}
		fmt.Fprintf(&b, "        map.put(%s, new MetricInfo(%s, %s, %s));\n",
			javaQuote(mt.MetricName),
			javaQuote(mt.MetricName),
			inst,
			javaQuote(mt.Unit),
		)
	}
	b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")

	writeSpanBuilder := func(methodName string, groups []group, ann string) {
		fmt.Fprintf(&b, "\n    private static Map<String, List<String>> %s() {\n", methodName)
		b.WriteString("        Map<String, List<String>> map = new LinkedHashMap<>();\n")
		for _, g := range groups {
			fmt.Fprintf(&b, "        map.put(%s, %s);\n", javaQuote(g.Annotations[ann]), javaStringList(requiredNames(g)))
		}
		b.WriteString("        return Collections.unmodifiableMap(map);\n    }\n")
	}

	writeSpanBuilder("buildSpanRequired", m.spans, "o11y.span.kind")
	writeSpanBuilder("buildRumSpanRequired", m.rumSpans, "o11y.rum.span")

	reserved := appregistry.ReservedNamespaces()
	b.WriteString("\n    private static Set<String> buildAppReservedNamespaces() {\n")
	b.WriteString("        Set<String> set = new LinkedHashSet<>();\n")
	for _, ns := range reserved {
		fmt.Fprintf(&b, "        set.add(%s);\n", javaQuote(ns))
	}
	b.WriteString("        return Collections.unmodifiableSet(set);\n    }\n")

	b.WriteString("}\n")
	return b.String(), nil
}

