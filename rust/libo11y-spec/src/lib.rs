//! The libo11y telemetry specification for Rust.
//!
//! This crate carries everything the libo11y specification registry
//! (`spec/registry` in the libo11y repository) defines, as Rust constants,
//! closed enums and static tables:
//!
//! - the spec identity: [`SCHEMA_URL`], [`SPEC_VERSION`], [`SEMCONV_VERSION`]
//!   and [`EVENT_NAME_KEY`];
//! - one enum per closed value set, such as [`Outcome`] and [`Environment`],
//!   each with `KEY`, `ALL`, `as_str`, [`Display`](fmt::Display) and
//!   [`FromStr`];
//! - attribute keys in [`attr`], event names in [`event`] and metric names
//!   in [`metric`];
//! - the tables the libo11y runtime enforces: the resource taxonomy
//!   ([`RESOURCE`], [`REQUIRED_TIER0`]), the sensitivity classes
//!   ([`SENSITIVITY`], [`sensitivity_of`]), the event, metric and span
//!   contracts ([`EVENTS`], [`METRICS`], [`SPAN_REQUIRED`],
//!   [`RUM_SPAN_REQUIRED`]), and the application registry rules
//!   ([`APP_REGISTRY_SCHEMA`], [`APP_RESERVED_NAMESPACES`]).
//!
//! The constants and tables are generated by specgen from the registry, the
//! same source as the Go and TypeScript implementations, so every language
//! names and classifies attributes identically.
//!
//! ```
//! use libo11y_spec::{Outcome, Sensitivity, attr, sensitivity_of};
//!
//! assert_eq!(attr::OUTCOME, "o11y.outcome");
//! assert_eq!("success".parse::<Outcome>(), Ok(Outcome::Success));
//! assert_eq!(sensitivity_of("host.ip"), Some(Sensitivity::Pii));
//! assert_eq!(sensitivity_of("http.request.header.authorization"), Some(Sensitivity::Secret));
//! ```

