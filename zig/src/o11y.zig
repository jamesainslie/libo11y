/// Returns a copy of `ctx` whose log records bypass level gates on every leg.
pub fn forceEmit(ctx: Context) Context {
    return ctx.withForceEmit();
}

// Wide events (`Record`).
pub const Record = record_mod.Record;
pub const RecordHandle = record_mod.RecordHandle;

/// Attaches `rec` to `ctx` and returns the new context.
pub fn startRecord(ctx: Context, rec: *Record) Context {
    return ctx.withRecord(rec);
}

/// Returns a non-nil `RecordHandle` for `ctx`; all methods are silent no-ops
/// when no record is attached.
pub fn recordFromContext(ctx: Context) RecordHandle {
    return .{ .ptr = ctx.record };
}

