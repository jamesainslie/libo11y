//!
//! Provides one-call OpenTelemetry setup (`o11y.setup` / `o11y.init`),
//! explicit context (`o11y.Context`), structured logging with console JSON
//! and OTLP fan-out, `std.log` bridge (`o11y.std_options` + `o11y.bindThread`),
//! sensitivity policy enforcement (`o11y.spec` + application registries),
//! capture-time redaction (`o11y.redact`), events and wide events (`o11y.Record`),
//! semantic-convention process metrics, propagation with baggage egress
//! filtering, and signal-driven graceful shutdown (`o11y.shutdownOnSignals`).

