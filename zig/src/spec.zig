//! The libo11y telemetry specification for Zig.
//!
//! This namespace carries everything the libo11y specification registry
//! (`spec/registry` in the libo11y repository) defines, as constants, closed
//! enums and static tables:
//!
//! - the spec identity: `schema_url`, `spec_version`, `semconv_version` and
//!   `event_name_key`;
//! - one enum per closed value set, such as `Outcome` and `Environment`,
//!   each with `key`, `all`, `asStr` and `parse`;
//! - attribute keys in `attr`, event names in `event` and metric names in
//!   `metric`;
//! - the tables the libo11y runtime enforces: the resource taxonomy
//!   (`resource`, `required_tier0`), the sensitivity and cardinality classes
//!   (`sensitivity`, `sensitivityOf`, `cardinality`, `cardinalityOf`), the
//!   event, metric and span contracts (`events`, `metrics`, `span_required`,
//!   `rum_span_required`), the application registry rules
//!   (`app_registry_schema`, `app_reserved_namespaces`), and the code points
//!   Go's `unicode.IsPrint` accepts (`go_print_ranges`, `isGoPrint`).
//!
//! The constants and tables are generated by specgen from the registry into
//! `spec/generated/`, the same source as the Go, TypeScript and Rust
//! implementations, so every language names and classifies attributes
//! identically. This file is hand-written: it defines the types the tables
//! use and re-exports every generated declaration by name, because Zig has
//! no glob re-export. A test below and one in specgen fail when a generated
//! declaration is missing here.

