test "span shapes match the registry" {
    try testing.expect(contains(spanRequired("server") orelse &.{}, "url.path"));
    try testing.expect(contains(rumSpanRequired("view") orelse &.{}, "session.id"));
    try testing.expect(spanRequired("view") == null);
