/// How the redaction layer treats an attribute. A key the spec does not
/// classify has no class: `sensitivityOf` returns null for it.
///
/// The tags are ordered from least to most sensitive and spelled as the
/// registry spells the classes. The set is exhaustive: the redaction layer
/// must decide what to do with every class, so a new class makes every
/// `switch` on this type stop compiling until it handles the class.
pub const Sensitivity = enum {
    /// Safe to emit anywhere.
    public,
    /// Operational detail that stays inside the organization.
    internal,
    /// Personal data: dropped, hashed or kept according to the PII mode.
    pii,
    /// Credentials and other secrets: dropped on every signal.
    secret,

    /// Every class, from least to most sensitive.
    pub const all: []const Sensitivity = &.{ .public, .internal, .pii, .secret };

    /// Returns the class as the registry spells it.
    pub fn asStr(self: Sensitivity) []const u8 {
        return @tagName(self);
    }

    /// Returns the class the registry spells `s`, or null when `s` is not one.
    pub fn parse(s: []const u8) ?Sensitivity {
        return std.meta.stringToEnum(Sensitivity, s);
    }
};

/// How many distinct values an attribute may take. A key the spec does not
/// classify has no class: `cardinalityOf` returns null for it.
///
/// The tags are ordered from the smallest budget to the largest and spelled
/// as the registry spells the classes.
pub const Cardinality = enum {
    /// A closed value set.
    @"enum",
    /// An open set with a known, small bound, such as a tenant or a region.
    bounded,
    /// No useful bound, such as an ID or a URL path. Never a metric label.
    unbounded,

    /// Every class, from the smallest budget to the largest.
    pub const all: []const Cardinality = &.{ .@"enum", .bounded, .unbounded };

    /// Returns the class as the registry spells it.
    pub fn asStr(self: Cardinality) []const u8 {
        return @tagName(self);
    }

    /// Returns the class the registry spells `s`, or null when `s` is not one.
    pub fn parse(s: []const u8) ?Cardinality {
        return std.meta.stringToEnum(Cardinality, s);
    }
};

/// A spec requirement level, spelled as the registry spells it.
pub const Requirement = enum {
    /// The attribute must be present.
    required,
    /// The attribute must be present when its condition holds.
    conditionally_required,
    /// The attribute should be present.
    recommended,
    /// The attribute is present only when the user asks for it.
    opt_in,

    /// Every level, from strictest to loosest.
    pub const all: []const Requirement = &.{ .required, .conditionally_required, .recommended, .opt_in };

    /// Returns the level as the registry spells it.
    pub fn asStr(self: Requirement) []const u8 {
        return @tagName(self);
    }

    /// Returns the level the registry spells `s`, or null when `s` is not one.
    pub fn parse(s: []const u8) ?Requirement {
        return std.meta.stringToEnum(Requirement, s);
    }
};

/// The kind of instrument a registered metric uses.
pub const Instrument = enum {
    /// A monotonic counter.
    counter,
    /// A counter that can go down.
    up_down_counter,
    /// A histogram.
    histogram,
    /// A gauge.
    gauge,

    /// Every instrument kind.
    pub const all: []const Instrument = &.{ .counter, .up_down_counter, .histogram, .gauge };

    /// Returns the instrument kind as the registry spells it.
    pub fn asStr(self: Instrument) []const u8 {
        return switch (self) {
            .counter => "counter",
            .up_down_counter => "updowncounter",
            .histogram => "histogram",
            .gauge => "gauge",
        };
    }

    /// Returns the instrument kind the registry spells `s`, or null when `s`
    /// is not one.
    pub fn parse(s: []const u8) ?Instrument {
        for (all) |value| {
            if (std.mem.eql(u8, value.asStr(), s)) return value;
        }
        return null;
    }
};

/// One attribute's place in the resource taxonomy.
pub const ResourceAttr = struct {
    /// The attribute key.
    key: []const u8,
    /// The tier the attribute belongs to, such as `tier0`.
    tier: []const u8,
    /// How strongly the spec asks for the attribute.
    requirement: Requirement,
    /// Where the value comes from, such as `option-or-env`.
    source: []const u8,
    /// Whether the attribute identifies the entity (`identifying`) or
    /// describes it (`descriptive`).
    role: []const u8,
};

/// A registered event's contract.
pub const EventInfo = struct {
    /// The event name.
    name: []const u8,
    /// The literal attribute keys the event must carry.
    required: []const []const u8,
    /// The template attributes the event must carry: each is satisfied by
    /// at least one `<template>.<key>` attribute, never by the bare name.
    required_templates: []const []const u8,
};

/// A registered metric.
pub const MetricInfo = struct {
    /// The metric name.
    name: []const u8,
    /// The instrument the metric uses.
    instrument: Instrument,
    /// The UCUM unit, such as `s` or `{violation}`.
    unit: []const u8,
};

/// A span shape the spec registers and the attributes required on it.
pub const SpanShape = struct {
    /// The shape's name: a span kind such as `server` in `span_required`,
    /// a RUM shape such as `view` in `rum_span_required`.
    name: []const u8,
    /// The attributes required on the span.
    required: []const []const u8,
};

/// One entry of the `sensitivity` table.
pub const SensitivityEntry = struct {
    /// The attribute key.
    key: []const u8,
    /// The class the spec gives the key.
    class: Sensitivity,
};

/// One entry of the `cardinality` table.
pub const CardinalityEntry = struct {
    /// The attribute key.
    key: []const u8,
    /// The class the spec gives the key.
    class: Cardinality,
};

/// One entry of the `legacy_keys` table.
pub const LegacyKey = struct {
    /// The key a pre-spec libo11y release emitted.
    key: []const u8,
    /// The spec key that replaces it.
    replacement: []const u8,
};

/// Returns a function that orders a key against an entry of type `T` by the
/// entry's key, for the binary searches over the sorted tables.
fn orderByKey(comptime T: type) fn ([]const u8, T) std.math.Order {
    return struct {
        fn order(key: []const u8, entry: T) std.math.Order {
            return std.mem.order(u8, key, entry.key);
        }
    }.order;
}

/// Orders a key against a string, for the binary search over a sorted list.
fn orderStrings(key: []const u8, item: []const u8) std.math.Order {
    return std.mem.order(u8, key, item);
}

/// Returns the sensitivity class the spec gives `key`, or null when the
/// spec does not classify it.
pub fn sensitivityOf(key: []const u8) ?Sensitivity {
    const i = std.sort.binarySearch(SensitivityEntry, sensitivity, key, orderByKey(SensitivityEntry)) orelse return null;
    return sensitivity[i].class;
}

/// Returns the cardinality class the spec gives `key`, or null when the
/// spec does not classify it.
pub fn cardinalityOf(key: []const u8) ?Cardinality {
    const i = std.sort.binarySearch(CardinalityEntry, cardinality, key, orderByKey(CardinalityEntry)) orelse return null;
    return cardinality[i].class;
}

/// Returns the spec key that replaces `key`, when `key` is one a pre-spec
/// libo11y release emitted.
pub fn legacyReplacement(key: []const u8) ?[]const u8 {
    const i = std.sort.binarySearch(LegacyKey, legacy_keys, key, orderByKey(LegacyKey)) orelse return null;
    return legacy_keys[i].replacement;
}

/// Returns the resource taxonomy entry for `key`.
pub fn resourceAttr(key: []const u8) ?*const ResourceAttr {
    for (resource) |*entry| {
        if (std.mem.eql(u8, entry.key, key)) return entry;
    }
    return null;
}

/// Returns the contract of the registered event `name`.
pub fn eventInfo(name: []const u8) ?*const EventInfo {
    for (events) |*entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry;
    }
    return null;
}

/// Returns the registration of the metric `name`.
pub fn metricInfo(name: []const u8) ?*const MetricInfo {
    for (metrics) |*entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry;
    }
    return null;
}

/// Returns the attributes required on a span of the registered kind `kind`.
pub fn spanRequired(kind: []const u8) ?[]const []const u8 {
    return shapeRequired(span_required, kind);
}

/// Returns the attributes required on the RUM span shape `shape`.
pub fn rumSpanRequired(shape: []const u8) ?[]const []const u8 {
    return shapeRequired(rum_span_required, shape);
}

fn shapeRequired(shapes: []const SpanShape, name: []const u8) ?[]const []const u8 {
    for (shapes) |shape| {
        if (std.mem.eql(u8, shape.name, name)) return shape.required;
    }
    return null;
}

/// Reports whether an application registry may not claim `namespace`.
pub fn isReservedNamespace(namespace: []const u8) bool {
    return std.sort.binarySearch([]const u8, app_reserved_namespaces, namespace, orderStrings) != null;
}

/// Orders a code point against an inclusive range: equal when inside it.
fn orderInRange(c: u21, range: [2]u21) std.math.Order {
    if (c < range[0]) return .lt;
    if (c > range[1]) return .gt;
    return .eq;
}

/// Reports whether Go's `unicode.IsPrint` accepts the code point `c`, in the
/// Unicode version of the Go toolchain that generated the spec artifacts.
/// Go's `%q` quoting, which libo11y's error and violation texts use, leaves
/// these characters unescaped, except `"` and `\`.
pub fn isGoPrint(c: u21) bool {
    return std.sort.binarySearch([2]u21, go_print_ranges, c, orderInRange) != null;
}

const testing = std.testing;

/// Fails unless every value of the closed set `E` survives `asStr` then
/// `parse`, the values are distinct, `all` lists every tag, and an unknown
/// string is rejected.
fn expectRoundTrips(comptime E: type) !void {
    try testing.expectEqual(std.meta.fieldNames(E).len, E.all.len);
    for (E.all, 0..) |value, i| {
        try testing.expectEqual(@as(?E, value), E.parse(value.asStr()));
        for (E.all[0..i]) |earlier| {
            try testing.expect(!std.mem.eql(u8, earlier.asStr(), value.asStr()));
        }
    }
    try testing.expectEqual(@as(?E, null), E.parse("\x00not a value"));
}

fn expectSortedUnique(keys: anytype) !void {
    if (keys.len < 2) return;
    for (keys[0 .. keys.len - 1], keys[1..]) |a, b| {
        try testing.expect(std.mem.order(u8, a, b) == .lt);
    }
}

fn expectSortedUniqueKeys(entries: anytype) !void {
    if (entries.len < 2) return;
    for (entries[0 .. entries.len - 1], entries[1..]) |a, b| {
        try testing.expect(std.mem.order(u8, a.key, b.key) == .lt);
    }
}

fn contains(list: []const []const u8, item: []const u8) bool {
    for (list) |entry| {
        if (std.mem.eql(u8, entry, item)) return true;
    }
    return false;
}

test "spec re-exports every generated declaration" {
    inline for (.{ generated_spec, generated_tables, generated_goprint }) |file| {
        inline for (comptime std.meta.declarations(file)) |name| {
            if (!@hasDecl(@This(), name)) {
                std.debug.print("spec.zig does not re-export {s}\n", .{name});
                return error.MissingReExport;
            }
        }
    }
}

test "lookup tables are sorted for binary search" {
    try expectSortedUniqueKeys(sensitivity);
    try expectSortedUniqueKeys(cardinality);
    try expectSortedUniqueKeys(legacy_keys);
    try expectSortedUnique(app_reserved_namespaces);
}

test "sensitivity classes match the registry" {
    try testing.expectEqual(@as(?Sensitivity, .pii), sensitivityOf("host.ip"));
    try testing.expectEqual(@as(?Sensitivity, .secret), sensitivityOf("http.request.header.authorization"));
    try testing.expectEqual(@as(?Sensitivity, .public), sensitivityOf("service.name"));
    try testing.expectEqual(@as(?Sensitivity, .internal), sensitivityOf("k8s.pod.uid"));
    try testing.expectEqual(@as(?Sensitivity, null), sensitivityOf("checkout.order.id"));
    try testing.expectEqual(@as(?Sensitivity, null), sensitivityOf(""));
}

test "cardinality classes match the registry" {
    try testing.expectEqual(@as(?Cardinality, .@"enum"), cardinalityOf(attr.outcome));
    try testing.expectEqual(@as(?Cardinality, .unbounded), cardinalityOf("url.path"));
    try testing.expectEqual(@as(?Cardinality, null), cardinalityOf("checkout.order.id"));
    for (cardinality) |entry| {
        try testing.expect(sensitivityOf(entry.key) != null);
    }
}

test "every resource attribute is classified" {
    for (resource) |entry| {
        try testing.expect(sensitivityOf(entry.key) != null);
    }
}

test "resource taxonomy matches the registry" {
    const name = resourceAttr("service.name") orelse return error.ServiceNameMissing;
    try testing.expectEqualStrings("tier0", name.tier);
    try testing.expectEqual(Requirement.required, name.requirement);
    try testing.expectEqualStrings("identifying", name.role);
    const tenant = resourceAttr("o11y.tenant.id") orelse return error.TenantIdMissing;
    try testing.expectEqual(Requirement.opt_in, tenant.requirement);
    try testing.expect(resourceAttr("process.command_line") == null);
    try testing.expect(contains(required_tier0, "service.name"));
    try testing.expect(contains(required_tier0, "deployment.environment.name"));
    try testing.expect(!contains(required_tier0, "telemetry.distro.name"));
}

test "environment values agree with the enum" {
    try testing.expectEqual(environment_values.len, Environment.all.len);
    for (Environment.all, environment_values) |value, text| {
        try testing.expectEqualStrings(text, value.asStr());
    }
    try testing.expectEqualStrings("deployment.environment.name", Environment.key);
    try testing.expectEqual(@as(?Environment, .production), Environment.parse("production"));
}

test "identity constants agree" {
    try testing.expect(std.mem.endsWith(u8, schema_url, "/" ++ spec_version));
    try testing.expectEqualStrings("1.41.0", semconv_version);
    try testing.expectEqualStrings("event.name", event_name_key);
    try testing.expectEqualStrings(Outcome.key, attr.outcome);
}

test "event contracts match the registry" {
    const summary = eventInfo(event.request_summary) orelse return error.RequestSummaryMissing;
    try testing.expect(contains(summary.required, attr.outcome));
    try testing.expectEqual(0, summary.required_templates.len);
    const configured = eventInfo(event.telemetry_configured) orelse return error.TelemetryConfiguredMissing;
    try testing.expectEqual(1, configured.required_templates.len);
    try testing.expectEqualStrings(attr.config, configured.required_templates[0]);
    try testing.expect(eventInfo("o11y.not.registered") == null);
}

test "metric registrations match the registry" {
    const violations = metricInfo(metric.schema_violations) orelse return error.SchemaViolationsMissing;
    try testing.expectEqual(Instrument.counter, violations.instrument);
    try testing.expectEqualStrings("{violation}", violations.unit);
    const lcp = metricInfo(metric.rum_vital_lcp) orelse return error.LcpMissing;
    try testing.expectEqual(Instrument.histogram, lcp.instrument);
    try testing.expect(metricInfo("o11y.not.registered") == null);
