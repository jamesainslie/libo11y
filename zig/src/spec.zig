test "app registry rules match go" {
    try testing.expectEqualStrings("libo11y.app-registry/v1", app_registry_schema);
    for ([_][]const u8{ "o11y", "otel", "http", "k8s", "gen_ai" }) |reserved| {
        try testing.expect(isReservedNamespace(reserved));
    }
    try testing.expect(!isReservedNamespace("checkout"));
}

test "go print ranges are sorted and disjoint" {
    try testing.expect(go_print_ranges.len > 0);
    for (go_print_ranges, 0..) |range, i| {
        // A range's bounds may be equal; ranges neither overlap nor touch.
        try testing.expect(range[0] <= range[1]);
        if (i > 0) try testing.expect(go_print_ranges[i - 1][1] + 1 < range[0]);
    }
}

test "isGoPrint matches go" {
    for ([_]u21{ ' ', 'a', '~', 0xa1, 0xe9, 0x1f600, '"', '\\' }) |printable| {
        try testing.expect(isGoPrint(printable));
    }
    for ([_]u21{ 0, 0x7, '\t', 0x7f, 0x85, 0xa0, 0xad, 0xfeff, 0x10ffff, 0x1fae9 }) |unprintable| {
        try testing.expect(!isGoPrint(unprintable));
    }
}

test "table keys are unique" {
    inline for (.{ resource, events, metrics, span_required, rum_span_required }) |table| {
        for (table, 0..) |entry, i| {
            const a = if (@hasField(@TypeOf(entry), "key")) entry.key else entry.name;
            for (table[0..i]) |earlier| {
                const b = if (@hasField(@TypeOf(earlier), "key")) earlier.key else earlier.name;
                try testing.expect(!std.mem.eql(u8, a, b));
            }
        }
    }
}

test "closed value sets round trip" {
    try expectRoundTrips(Sensitivity);
    try expectRoundTrips(Cardinality);
    try expectRoundTrips(Requirement);
    try expectRoundTrips(Instrument);
    inline for (comptime std.meta.declarations(generated_spec)) |name| {
        const decl = @field(generated_spec, name);
        if (@TypeOf(decl) == type and @typeInfo(decl) == .@"enum") try expectRoundTrips(decl);
    }
}

