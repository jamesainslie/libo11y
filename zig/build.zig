//! Build script for the libo11y Zig package.
//!
//! It exports the `o11y`, `o11ytest`, and `o11yhttp` modules by default, plus
//! the optional option-gated integration modules `o11yhttpz` (`-Dhttpz`),
//! `o11ypg` (`-Dpg`), and `o11ysqlite` (`-Dsqlite`). The repository root's
//! build.zig re-exports every module this script adds with `b.addModule`, so
//! consumers that fetch the repository get the same names.

const std = @import("std");

/// Options for `addBuildInfo`.
pub const BuildInfoOptions = struct {
    /// Explicit service version string (for example from a release manifest).
    /// When null, `service.version` is left empty unless set in code or env.
    service_version: ?[]const u8 = null,
    /// Directory passed to `git -C` when probing VCS metadata. Defaults to
    /// the build root.
    git_dir: ?[]const u8 = null,
    /// Import name added to `compile.root_module`.
    module_name: []const u8 = "o11y_build_info",
};

/// Records build-time identity (`service.version`, `vcs.ref.head.revision`,
/// `o11y.build.time`, `o11y.build.modified`) from git into a build-options
/// module attached to `compile`. Fails gracefully when git is unavailable or
/// the directory is not a git repository, leaving unavailable fields empty.
pub fn addBuildInfo(b: *std.Build, compile: *std.Build.Step.Compile, options: BuildInfoOptions) void {
    const opts = b.addOptions();
    opts.addOption([]const u8, "version", options.service_version orelse "");
    const revision = runGit(b, options.git_dir, &.{ "rev-parse", "HEAD" }) orelse "";
    const commit_time = runGit(b, options.git_dir, &.{ "show", "-s", "--format=%cI", "HEAD" }) orelse "";
    const status_out = runGit(b, options.git_dir, &.{ "status", "--porcelain" });
    const modified: ?bool = if (status_out) |s| s.len > 0 else null;
    opts.addOption([]const u8, "revision", revision);
    opts.addOption([]const u8, "time", commit_time);
    opts.addOption(?bool, "modified", modified);
    compile.root_module.addOptions(options.module_name, opts);
}

fn runGit(b: *std.Build, git_dir: ?[]const u8, args: []const []const u8) ?[]const u8 {
    var argv_buf: [12][]const u8 = undefined;
    var n: usize = 0;
    argv_buf[n] = "git";
    n += 1;
    if (git_dir) |dir| {
        argv_buf[n] = "-C";
        argv_buf[n + 1] = dir;
        n += 2;
    }
    if (n + args.len > argv_buf.len) return null;
    for (args) |a| {
        argv_buf[n] = a;
        n += 1;
    }
    var exit_code: u8 = 0;
    const out = b.runAllowFail(argv_buf[0..n], &exit_code, .ignore) catch return null;
    if (exit_code != 0) return null;
    return std.mem.trim(u8, out, " \t\r\n");
}

pub fn build(b: *std.Build) !void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const protobuf = b.dependency("protobuf", .{
        .target = target,
        .optimize = optimize,
    }).module("protobuf");

    const tls = b.dependency("tls", .{
        .target = target,
        .optimize = optimize,
    }).module("tls");

    // The OTLP bindings generated by opentelemetry-zig, vendored under
    // src/proto/ (see src/proto/README.md). The module is internal: it is
    // created, not added, so the root shim does not re-export it.
    const proto = b.createModule(.{
        .root_source_file = b.path("src/proto/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "protobuf", .module = protobuf },
        },
    });

    // Private OTLP wire framing module shared by `o11y` and `o11ytest`.
    // Created with `createModule`, never added, so consumers cannot import it.
    const o11y_wire = b.createModule(.{
        .root_source_file = b.path("src/pipeline/otlp/wire/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "tls", .module = tls },
        },
    });

    const manifest = @import("build.zig.zon");
    const options = b.addOptions();
    options.addOption([]const u8, "version", manifest.version);

    const o11y = b.addModule("o11y", .{
        .root_source_file = b.path("src/o11y.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "opentelemetry-proto", .module = proto },
            .{ .name = "protobuf", .module = protobuf },
            .{ .name = "tls", .module = tls },
            .{ .name = "o11y_wire", .module = o11y_wire },
            .{ .name = "build_options", .module = options.createModule() },
        },
    });

    const o11ytest = b.addModule("o11ytest", .{
        .root_source_file = b.path("src/o11ytest/o11ytest.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "o11y", .module = o11y },
            .{ .name = "opentelemetry-proto", .module = proto },
            .{ .name = "protobuf", .module = protobuf },
            .{ .name = "tls", .module = tls },
            .{ .name = "o11y_wire", .module = o11y_wire },
        },
    });

    const o11yhttp = b.addModule("o11yhttp", .{
        .root_source_file = b.path("src/o11yhttp/o11yhttp.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "o11y", .module = o11y },
        },
    });

    // Private SQL sanitizer and database telemetry module shared by `o11ypg`
    // and `o11ysqlite`. Created with `createModule`, never added, so consumers
    // cannot import it.
    const o11y_db = b.createModule(.{
        .root_source_file = b.path("src/db/root.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "o11y", .module = o11y },
        },
    });

    // `-Dtest-filter=<text>` runs only the tests whose name contains the
    // text. Give it more than once for several filters.
    const test_filters = b.option(
        []const []const u8,
        "test-filter",
        "Run only the tests whose name contains this text",
    ) orelse &.{};

    const tests = b.addTest(.{ .root_module = o11y, .filters = test_filters });
    const test_step = b.step("test", "Run the libo11y tests");
    test_step.dependOn(&b.addRunArtifact(tests).step);

    const wire_tests = b.addTest(.{ .filters = test_filters, .root_module = o11y_wire });
    test_step.dependOn(&b.addRunArtifact(wire_tests).step);

    const db_tests = b.addTest(.{ .filters = test_filters, .root_module = o11y_db });
    test_step.dependOn(&b.addRunArtifact(db_tests).step);

    const db_telemetry_tests = b.addTest(.{ .filters = test_filters, .root_module = b.createModule(.{
        .root_source_file = b.path("src/db/telemetry_test.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "o11y", .module = o11y },
            .{ .name = "o11y_db", .module = o11y_db },
            .{ .name = "o11ytest", .module = o11ytest },
        },
    }) });
    test_step.dependOn(&b.addRunArtifact(db_telemetry_tests).step);

    const o11ytest_tests = b.addTest(.{ .filters = test_filters, .root_module = o11ytest });
    test_step.dependOn(&b.addRunArtifact(o11ytest_tests).step);

    const o11yhttp_tests = b.addTest(.{ .filters = test_filters, .root_module = o11yhttp });
    test_step.dependOn(&b.addRunArtifact(o11yhttp_tests).step);

    const o11yhttp_integration_tests = b.addTest(.{ .filters = test_filters, .root_module = b.createModule(.{
        .root_source_file = b.path("src/o11yhttp/integration_test.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "o11y", .module = o11y },
            .{ .name = "o11yhttp", .module = o11yhttp },
            .{ .name = "o11ytest", .module = o11ytest },
        },
    }) });
    test_step.dependOn(&b.addRunArtifact(o11yhttp_integration_tests).step);

    // Optional integration modules gated behind explicit build options so
    // `b.lazyDependency` is never invoked unless a consumer asks for them.
    const httpz_enabled = b.option(
        bool,
        "httpz",
        "Enable the o11yhttpz module (fetches http.zig)",
    ) orelse false;
    if (httpz_enabled) {
        if (b.lazyDependency("httpz", .{
            .target = target,
            .optimize = optimize,
        })) |httpz_dep| {
            const httpz_mod = httpz_dep.module("httpz");
            const o11yhttpz = b.addModule("o11yhttpz", .{
                .root_source_file = b.path("src/o11yhttpz/o11yhttpz.zig"),
                .target = target,
                .optimize = optimize,
                .imports = &.{
                    .{ .name = "o11y", .module = o11y },
                    .{ .name = "o11yhttp", .module = o11yhttp },
                    .{ .name = "httpz", .module = httpz_mod },
                },
            });
            const o11yhttpz_tests = b.addTest(.{ .filters = test_filters, .root_module = o11yhttpz });
            test_step.dependOn(&b.addRunArtifact(o11yhttpz_tests).step);

            const o11yhttpz_integration_tests = b.addTest(.{ .filters = test_filters, .root_module = b.createModule(.{
                .root_source_file = b.path("src/o11yhttpz/integration_test.zig"),
                .target = target,
                .optimize = optimize,
                .imports = &.{
                    .{ .name = "o11y", .module = o11y },
                    .{ .name = "o11yhttp", .module = o11yhttp },
                    .{ .name = "o11yhttpz", .module = o11yhttpz },
                    .{ .name = "o11ytest", .module = o11ytest },
                    .{ .name = "httpz", .module = httpz_mod },
                },
            }) });
            test_step.dependOn(&b.addRunArtifact(o11yhttpz_integration_tests).step);
        }
    }

    const pg_enabled = b.option(
        bool,
        "pg",
        "Enable the o11ypg module (fetches pg.zig)",
    ) orelse false;
    if (pg_enabled) {
        if (b.lazyDependency("pg", .{
            .target = target,
            .optimize = optimize,
        })) |pg_dep| {
            const pg_mod = pg_dep.module("pg");
            const o11ypg = b.addModule("o11ypg", .{
                .root_source_file = b.path("src/o11ypg/o11ypg.zig"),
                .target = target,
                .optimize = optimize,
                .imports = &.{
                    .{ .name = "o11y", .module = o11y },
                    .{ .name = "o11y_db", .module = o11y_db },
                    .{ .name = "pg", .module = pg_mod },
                },
            });
            const o11ypg_tests = b.addTest(.{ .filters = test_filters, .root_module = o11ypg });
            test_step.dependOn(&b.addRunArtifact(o11ypg_tests).step);

            const o11ypg_integration_tests = b.addTest(.{ .filters = test_filters, .root_module = b.createModule(.{
                .root_source_file = b.path("src/o11ypg/integration_test.zig"),
                .target = target,
                .optimize = optimize,
                .imports = &.{
                    .{ .name = "o11y", .module = o11y },
                    .{ .name = "o11y_db", .module = o11y_db },
                    .{ .name = "o11ypg", .module = o11ypg },
                    .{ .name = "o11ytest", .module = o11ytest },
                    .{ .name = "pg", .module = pg_mod },
                },
            }) });
            const o11ypg_run = b.addRunArtifact(o11ypg_integration_tests);
            // Reads O11YPG_TEST_DSN at run time so live PG tests re-run when env changes.
            o11ypg_run.has_side_effects = true;
            test_step.dependOn(&o11ypg_run.step);
        }
    }

    const sqlite_enabled = b.option(
        bool,
        "sqlite",
        "Enable the o11ysqlite module (fetches zig-sqlite)",
    ) orelse false;
    if (sqlite_enabled) {
        if (b.lazyDependency("sqlite", .{
            .target = target,
            .optimize = optimize,
        })) |sqlite_dep| {
            const sqlite_mod = sqlite_dep.module("sqlite");
            const o11ysqlite = b.addModule("o11ysqlite", .{
                .root_source_file = b.path("src/o11ysqlite/o11ysqlite.zig"),
                .target = target,
                .optimize = optimize,
                .imports = &.{
                    .{ .name = "o11y", .module = o11y },
                    .{ .name = "o11y_db", .module = o11y_db },
                    .{ .name = "sqlite", .module = sqlite_mod },
                },
            });
            const o11ysqlite_tests = b.addTest(.{ .filters = test_filters, .root_module = o11ysqlite });
            test_step.dependOn(&b.addRunArtifact(o11ysqlite_tests).step);

            const o11ysqlite_integration_tests = b.addTest(.{ .filters = test_filters, .root_module = b.createModule(.{
                .root_source_file = b.path("src/o11ysqlite/integration_test.zig"),
                .target = target,
                .optimize = optimize,
                .imports = &.{
                    .{ .name = "o11y", .module = o11y },
                    .{ .name = "o11y_db", .module = o11y_db },
                    .{ .name = "o11ysqlite", .module = o11ysqlite },
                    .{ .name = "o11ytest", .module = o11ytest },
                    .{ .name = "sqlite", .module = sqlite_mod },
                },
            }) });
            test_step.dependOn(&b.addRunArtifact(o11ysqlite_integration_tests).step);
        }
    }

    // Tests that read fixtures under test/, which the published package
    // leaves out. They build only when the test step runs.
    const fixture_tests = b.addTest(.{ .filters = test_filters, .root_module = b.createModule(.{
        .root_source_file = b.path("test/otlp_fixtures_test.zig"),
        .target = target,
        .optimize = optimize,
        .imports = &.{
            .{ .name = "opentelemetry-proto", .module = proto },
        },
    }) });
    test_step.dependOn(&b.addRunArtifact(fixture_tests).step);

    // The conformance suite reads the shared cases and vectors at run time.
    // The published package does not hold them, so the default is the
    // repository's conformance/ directory beside zig/. The path is only
    // resolved when the test step runs, so a consumer's build never needs
    // it.
    const conformance_dir: std.Build.LazyPath = if (b.option(
        []const u8,
        "conformance-dir",
        "The directory of shared conformance cases (default: the repository's conformance/)",
    )) |dir| b.graph.cwdRelativePath(dir) else b.path("../conformance");
    const conformance = b.addOptions();
    conformance.addOptionPathDirectory("dir", conformance_dir);
    const conformance_tests = b.addTest(.{
        // Only the suite itself. The unit tests of the files it imports run
        // in the o11y module's tests.
        .filters = &.{"conformance_test."},
        .root_module = b.createModule(.{
            .root_source_file = b.path("src/conformance_test.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{
                .{ .name = "conformance", .module = conformance.createModule() },
            },
        }),
    });
    const conformance_run = b.addRunArtifact(conformance_tests);
    // The build cannot see the files the suite reads, so it runs every time
    // rather than reporting a cached result for changed cases.
    conformance_run.has_side_effects = true;
    test_step.dependOn(&conformance_run.step);
}
