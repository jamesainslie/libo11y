package pack

import (
	"bytes"

	"github.com/jamesainslie/libo11y/ops/internal/dash"
)

// prometheusRulePath is the PrometheusRule the kustomization deploys.
const prometheusRulePath = "kubernetes/prometheusrule.yaml"

// ruleFileOrder is the order the PrometheusRule holds the rule files'
// groups in.
var ruleFileOrder = []string{rumRulesPath, gatewayRulesPath}

// kustomization renders kustomization.yaml: the PrometheusRule, and one
// ConfigMap per dashboard labelled for the Grafana dashboard sidecar. One
// ConfigMap per dashboard keeps each far under the 1 MiB object limit.
func kustomization(dashboards []dash.Dashboard) []byte {
	var b bytes.Buffer
	b.WriteString(`# Generated by opsgen. The libo11y RUM ops pack: one PrometheusRule and one
# ConfigMap per dashboard, labelled for the Grafana dashboard sidecar.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ` + prometheusRulePath + `
generatorOptions:
  disableNameSuffixHash: true
  labels:
    grafana_dashboard: "1"
    app.kubernetes.io/part-of: libo11y
configMapGenerator:
`)
	for _, d := range dashboards {
		b.WriteString("  - name: " + d.UID + "\n    files: [dashboards/" + d.UID + ".json]\n")
	}
	return b.Bytes()
}
