func artifacts(t *testing.T) map[string][]byte {
	t.Helper()
	arts, err := Build(thresholds.Default(), "0.1.0")
	if err != nil {
		t.Fatal(err)
	}
	out := map[string][]byte{}
	for _, a := range arts {
		out[a.Path] = a.Data
	}
	return out
}

// TestKustomization checks the generated kustomization lists the
// PrometheusRule and one ConfigMap per dashboard, in dashboard order, each
// naming a file the pack generates.
func TestKustomization(t *testing.T) {
	arts := artifacts(t)
	raw, ok := arts["kustomization.yaml"]
	if !ok {
		t.Fatal("no kustomization.yaml artifact")
	}
	if !strings.HasPrefix(string(raw), "# Generated by opsgen.") {
		t.Errorf("kustomization.yaml does not say it is generated:\n%s", raw)
	}
	var k struct {
		APIVersion       string   `yaml:"apiVersion"`
		Kind             string   `yaml:"kind"`
		Resources        []string `yaml:"resources"`
		GeneratorOptions struct {
			DisableNameSuffixHash bool              `yaml:"disableNameSuffixHash"`
			Labels                map[string]string `yaml:"labels"`
		} `yaml:"generatorOptions"`
		ConfigMapGenerator []struct {
			Name  string   `yaml:"name"`
			Files []string `yaml:"files"`
		} `yaml:"configMapGenerator"`
	}
	dec := yaml.NewDecoder(strings.NewReader(string(raw)))
	dec.KnownFields(true)
	if err := dec.Decode(&k); err != nil {
		t.Fatal(err)
	}
	if k.APIVersion != "kustomize.config.k8s.io/v1beta1" || k.Kind != "Kustomization" {
		t.Errorf("header %s %s", k.APIVersion, k.Kind)
	}
	if !slices.Equal(k.Resources, []string{"kubernetes/prometheusrule.yaml"}) {
		t.Errorf("resources %q", k.Resources)
	}
	if !k.GeneratorOptions.DisableNameSuffixHash || k.GeneratorOptions.Labels["grafana_dashboard"] != "1" || k.GeneratorOptions.Labels["app.kubernetes.io/part-of"] != "libo11y" {
		t.Errorf("generator options %+v", k.GeneratorOptions)
	}
	var names []string
	for _, g := range k.ConfigMapGenerator {
		names = append(names, g.Name)
		if want := []string{"dashboards/" + g.Name + ".json"}; !slices.Equal(g.Files, want) {
			t.Errorf("ConfigMap %s files %q, want %q", g.Name, g.Files, want)
		}
	}
	if !slices.Equal(names, UIDs) {
		t.Errorf("ConfigMaps %q, want one per dashboard in order %q", names, UIDs)
	}
	listed := slices.Clone(k.Resources)
	for _, g := range k.ConfigMapGenerator {
		listed = append(listed, g.Files...)
	}
	for _, p := range listed {
		if _, ok := arts[p]; !ok {
			t.Errorf("the kustomization lists %s, which the pack does not generate", p)
		}
	}
}

// TestPrometheusRuleArtifact checks the PrometheusRule holds the groups of
// every rule file, in file order.
func TestPrometheusRuleArtifact(t *testing.T) {
	raw, ok := artifacts(t)["kubernetes/prometheusrule.yaml"]
	if !ok {
		t.Fatal("no kubernetes/prometheusrule.yaml artifact")
	}
	var pr struct {
		Kind     string `yaml:"kind"`
		Metadata struct {
			Name string `yaml:"name"`
		} `yaml:"metadata"`
		Spec rules.File `yaml:"spec"`
	}
	if err := yaml.Unmarshal(raw, &pr); err != nil {
		t.Fatal(err)
	}
	files := RuleFiles(thresholds.Default(), "0.1.0")
	var want []rules.Group
	for _, p := range []string{rumRulesPath, gatewayRulesPath} {
		want = append(want, files[p].Groups...)
	}
	got, err := rules.File{Groups: pr.Spec.Groups}.YAML()
	if err != nil {
		t.Fatal(err)
	}
	wantYAML, err := rules.File{Groups: want}.YAML()
	if err != nil {
		t.Fatal(err)
	}
	if pr.Kind != "PrometheusRule" || pr.Metadata.Name != "libo11y-rum" {
		t.Errorf("kind %s name %s, want PrometheusRule libo11y-rum", pr.Kind, pr.Metadata.Name)
	}
	if string(got) != string(wantYAML) {
		t.Errorf("spec.groups differ from the rule files' groups in order\n got:\n%s\nwant:\n%s", got, wantYAML)
	}
}

// TestDashboardsSmall keeps each dashboard far under the 1 MiB object
// limit, so its ConfigMap fits even with client-side apply's annotation.
func TestDashboardsSmall(t *testing.T) {
	const limit = 256 << 10
	for p, b := range artifacts(t) {
		if strings.HasPrefix(p, "dashboards/") && len(b) > limit {
			t.Errorf("%s is %d bytes, over %d", p, len(b), limit)
		}
	}
}

// TestDatasourceExample keeps the hand-written provisioning example in
// step with the dashboards' datasource variables: one datasource per
// variable, whose UID and type are the variable's name and plugin.
func TestDatasourceExample(t *testing.T) {
	raw, err := os.ReadFile("../../datasources/example.yaml")
	if err != nil {
		t.Fatal(err)
	}
	var ex struct {
		Datasources []struct {
			UID  string `yaml:"uid"`
			Type string `yaml:"type"`
		} `yaml:"datasources"`
	}
	if err := yaml.Unmarshal(raw, &ex); err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, d := range ex.Datasources {
		got = append(got, d.UID+"/"+d.Type)
	}
	want := []string{varProm.Name + "/" + varProm.Query, varLoki.Name + "/" + varLoki.Query, varTempo.Name + "/" + varTempo.Query}
	if !slices.Equal(got, want) {
		t.Errorf("datasources %q, want %q", got, want)
	}
}
