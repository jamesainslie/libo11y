import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { attribute, duplicatePackages, groupSums, main, type SourceMap } from "./rn-bundle-size.ts";

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

/** Base64 VLQ of one value, as source maps write it. */
function vlq(value: number): string {
  let v = value < 0 ? (-value << 1) | 1 : value << 1;
  let out = "";
  do {
    let digit = v & 31;
    v >>>= 5;
    if (v > 0) digit |= 32;
    out += B64[digit];
  } while (v > 0);
  return out;
}

/**
 * The mappings of lines of segments, each [column] or [column, source], absolute, encoded relative
 * as the format requires: the column per line, the source across the whole map.
 */
function mappings(lines: readonly (readonly (readonly number[])[])[]): string {
  let source = 0;
  return lines
    .map((segments) => {
      let column = 0;
      return segments
        .map((s) => {
          let out = vlq((s[0] ?? 0) - column);
          column = s[0] ?? 0;
          if (s.length > 1) {
            out += vlq((s[1] ?? 0) - source) + vlq(0) + vlq(0);
            source = s[1] ?? 0;
          }
          return out;
        })
        .join(",");
    })
    .join(";");
}

const SOURCES = [
  "../../node_modules/@libo11y/core/dist/a.js",
  "node_modules/@opentelemetry/api/x.js",
  "app.js",
];
// Line 0: core 4, api 3, app 2 plus its newline. Line 1: core 2, then a segment with no source
// (2 and the newline unmapped). Line 2: one unmapped byte, then app from column 1: "zÉE", where É is
// one UTF-16 column and two UTF-8 bytes.
const CODE = "AAAABBBCC\nDDDD\nzzÉE";
const MAP: SourceMap = {
  version: 3,
  sources: SOURCES,
  mappings: mappings([
    [
      [0, 0],
      [4, 1],
      [7, 2],
    ],
    [[0, 0], [2]],
    [[1, 2]],
  ]),
};

test("every generated byte goes to the source of its segment, or to unmapped", () => {
  const a = attribute(CODE, MAP);
  assert.deepEqual(Object.fromEntries(a.bySource), {
    [SOURCES[0] ?? ""]: 6,
    [SOURCES[1] ?? ""]: 3,
    "app.js": 7,
  });
  assert.equal(a.unmapped, 4);
  assert.equal(a.total, Buffer.byteLength(CODE));
});

test("sourceRoot prefixes every source", () => {
  const a = attribute(CODE, { ...MAP, sourceRoot: "/root/" });
  assert.ok(a.bySource.has("/root/app.js"));
  assert.ok(
    attribute(CODE, { ...MAP, sources: [null, null, "app.js"] }).unmapped > 4,
    "a null source is unmapped",
  );
});

test("groups sum the bytes of sources inside node_modules/<group>/", () => {
  const sums = groupSums(attribute(CODE, MAP).bySource, ["@libo11y", "@opentelemetry", "@expo"]);
  assert.deepEqual(sums, { "@libo11y": 6, "@opentelemetry": 3, "@expo": 0 });
});

test("a package bundled from both its CommonJS and its ESM build is a duplicate", () => {
  assert.deepEqual(
    duplicatePackages([
      "node_modules/@opentelemetry/core/dist/index.cjs",
      "node_modules/@opentelemetry/core/dist/common/time.mjs",
      "node_modules/@opentelemetry/api/build/esm/index.js",
      "node_modules/@opentelemetry/sdk-trace/dist/index.mjs",
      "node_modules/@libo11y/web/node_modules/@opentelemetry/sdk-trace/dist/index.mjs",
      "node_modules/@libo11y/core/dist/telemetry.js",
    ]),
    ["@opentelemetry/core", "@opentelemetry/sdk-trace"],
  );
});

test("an index map, as Metro writes, attributes each section's segments from its offset", () => {
  const indexMap: SourceMap = {
    version: 3,
    sections: [
      {
        offset: { line: 0, column: 0 },
        map: {
          version: 3,
          sources: [SOURCES[0] ?? "", SOURCES[1] ?? ""],
          mappings: mappings([
            [
              [0, 0],
              [4, 1],
            ],
          ]),
        },
      },
      {
        offset: { line: 0, column: 7 },
        map: { version: 3, sources: ["app.js"], mappings: mappings([[[0, 0]]]) },
      },
      {
        offset: { line: 1, column: 0 },
        map: {
          version: 3,
          sources: [SOURCES[0] ?? "", "app.js"],
          mappings: mappings([[[0, 0], [2]], [[1, 1]]]),
        },
      },
    ],
  };
  assert.deepEqual(attribute(CODE, indexMap), attribute(CODE, MAP));
});

test("nested index maps are refused", () => {
  const nested: SourceMap = { version: 3, sections: [] };
  assert.throws(
    () => attribute(CODE, { version: 3, sections: [{ offset: { line: 0, column: 0 }, map: { ...nested } }] }),
    /nested/,
  );
});

function fixture(budgets: Record<string, number>): { dir: string; args: string[]; summary: string } {
  const dir = mkdtempSync(join(tmpdir(), "rn-bundle-size-"));
  writeFileSync(join(dir, "bundle.js"), CODE);
  writeFileSync(join(dir, "bundle.js.map"), JSON.stringify(MAP));
  writeFileSync(join(dir, "budget.json"), JSON.stringify({ unit: "bytes", budgets }));
  const summary = join(dir, "summary.md");
  return {
    dir,
    summary,
    args: [
      "--map",
      join(dir, "bundle.js.map"),
      "--bundle",
      join(dir, "bundle.js"),
      "--budget",
      join(dir, "budget.json"),
      "--summary",
      summary,
    ],
  };
}

test("--check passes within budget and appends the table to --summary", () => {
  const f = fixture({ "@libo11y": 6, "@opentelemetry": 3 });
  try {
    assert.equal(main([...f.args, "--check"]), 0);
    const md = readFileSync(f.summary, "utf8");
    assert.match(md, /\| @libo11y \| 6 \| 6 \| ok \|/);
    assert.match(md, /\| @opentelemetry \| 3 \| 3 \| ok \|/);
  } finally {
    rmSync(f.dir, { recursive: true, force: true });
  }
});

test("--check fails when a group is over its budget, and without --check it only reports", () => {
  const f = fixture({ "@libo11y": 5, "@opentelemetry": 3 });
  try {
    assert.equal(main([...f.args, "--check"]), 1);
    assert.match(readFileSync(f.summary, "utf8"), /\| @libo11y \| 6 \| 5 \| over \|/);
    assert.equal(main(f.args), 0);
  } finally {
    rmSync(f.dir, { recursive: true, force: true });
  }
});

test("a missing argument is a usage error", () => {
  assert.equal(main(["--map", "x.map"]), 2);
});
